-- ============================================================================
-- HARNESS 155 (round 156): THE MAGIC MISSILES (user rulings 2026-11-15).
--   The caster stands 60 m from every enemy (unit_distance); enemies 100 m
--   down the field. Types: TG a Terrorgheist (large, single entity), VA a
--   Vampire (single entity, on foot), GG Grave Guard (armour 90), ZB Zombies
--   (armour 0, value 75 = 0.6 per soldier), SW Swordsmen.
--   LS1 Hunting Spear: TG + GG -> ONE cast at TG (large first).
--   LS2 Hunting Spear: ZB + GG, no large -> ONE cast at GG (most armour).
--   LS3 Hunting Spear: TG with our Swordsmen overlapping it -> no cast.
--   SS1 Dead Eye: VA (900) + TG (600) + GG (1500, not single) -> ONE cast at VA.
--   SS2 Focused Shot (bonus v large): VA (1500) + TG (900) -> ONE cast at TG.
--   SS3 Dead Eye: the caster is moving -> no cast.
--   IS1 Bolt Storm: ZB + GG -> ONE cast at GG (value per soldier).
--   IS2 Bolt Storm: GG with our Swordsmen on it -> no cast.
--   IS3 Bolt Storm: the caster is in melee (the game's engaged_in_melee) -> no cast.
--   MF1 Crippling Throw: an enemy in melee -> ONE cast at it.
--   MF2 Crippling Throw: a fast enemy (8 m/s) 20 m from us -> ONE cast at it.
--   MF3 Crippling Throw: the caster in melee (engaged_in_melee) -> no cast.
--   MF4 Golden Blowpipe: an enemy in melee 3 m away (min_range 5 m) -> no cast.
--   MS1 Spear of Kurnous: an enemy in melee -> ONE cast at it.
--   MS2 Spear of Kurnous: shooting handgunners, not in melee -> ONE cast at them.
--   MS3 Spear of Kurnous: idle Swordsmen -> no cast.
--   RED (pre-156 = round 155): LS1, SS1, IS1, MF1, MS2 cast nothing.
-- ============================================================================
function run_h155()
  local L155 = os.getenv("H155_LIVE") or LIVE
  local A155 = os.getenv("H155_ANN") or ANN
  local RED155 = (os.getenv("H155_LIVE") ~= nil) or (os.getenv("H155_ANN") ~= nil)
  local HS = "wh_dlc03_weapon_abilities_hunting_spear"
  local DE = "wh3_dlc26_character_abilities_dead_eye"
  local FS = "wh2_dlc13_lord_abilities_kill_shot"
  local BS = "wh3_main_weapon_abilities_nuku_chos_crossbow"
  local CT = "wh3_main_character_abilities_crippling_throw"
  local GB = "wh2_dlc17_weapon_abilities_the_golden_blowpipe_of_ptoohee"
  local SK = "wh_dlc05_weapon_abilities_spear_of_kurnous"
  local CASTER = "wh2_dlc13_emp_cha_huntsmen_general_0"
  local TG = "wh_main_vmp_mon_terrorgheist"
  local VA = "wh_main_vmp_cha_vampire_0"
  local GG = "wh_main_vmp_inf_grave_guard_0"
  local ZB = "wh_main_vmp_inf_zombie"
  local SW = "wh_main_emp_inf_swordsmen"
  local GUNS = "wh_main_emp_inf_handgunners"
  local pre155 = checks
  local function cp(s, tok)
    local n, at = 0, 1
    while true do
      local i = raw_find(s, tok, at, true)
      if i == nil then return n end
      n = n + 1; at = i + #tok
    end
  end

  print("== HARNESS 155 - section 0zz3: the round-156 tokens ==")
  if not RED155 then
    for _, f in ipairs({ { name = "live", path = L155 }, { name = "ann", path = A155 } }) do
      local s = read_file(f.path)
      check("0zz3 " .. f.name .. ": 810 entries, the 5 new families wired, the SHOT table, the single class, R120, the re-check",
        cp(s, "\t{ marker = ") == 810
        and cp(s, 'trigger = "enemy_large_shot"') == 5 and cp(s, 'trigger = "enemy_single_shot"') == 2
        and cp(s, 'trigger = "enemy_infantry_shot"') == 1 and cp(s, 'trigger = "enemy_melee_or_fast"') == 2
        and cp(s, 'trigger = "enemy_melee_or_shooting"') == 1
        and raw_find(s, "enemy_large_shot = FOURTH.evaluate_enemy_large_shot,", 1, true) ~= nil
        and raw_find(s, "enemy_melee_or_shooting = FOURTH.evaluate_enemy_melee_or_shooting,", 1, true) ~= nil
        and raw_find(s, "-- GENERATED by tools/gen_shot_tables.py", 1, true) ~= nil
        and raw_find(s, "wh3_main_character_abilities_crippling_throw=1,0,0;", 1, true) ~= nil
        and raw_find(s, "wh2_dlc13_lord_abilities_kill_shot=0,1,0;", 1, true) ~= nil
        and raw_find(s, 'if cls == "single" then return FOURTH.class_keys.single[t] == true end', 1, true) ~= nil
        and raw_find(s, "FOURTH.ENEMY_CAST_R120 = 84 ", 1, true) ~= nil
        and raw_find(s, 'elseif eg_mode_now == "shot" then', 1, true) ~= nil
        and raw_find(s, "FOURTH.SHOT_SAFE_M = 10 ", 1, true) ~= nil)
    end
  end

  local FILES = { { path = A155, tag = "[annotated] " }, { path = L155, tag = "[live] " } }
  local n_ok, n_all = 0, 0
  local function done(ok) n_all = n_all + 1; if ok then n_ok = n_ok + 1 end end
  local function world(wname, units, enemies, marker, key, PATH, TAG, sv)
    local cards = {}
    for _, d in ipairs(units) do cards[#cards + 1] = { id = tostring(d.uid), state = "active", vis = true } end
    local W = make_world({ can_perform = true, units = units, enemies = enemies, cards = cards,
      bar = { { id = "b1", key = key } } })
    W.defaults_on = false
    print("== " .. TAG .. wname .. " ==")
    W.bm.get_player_alliance = function() return "OUR_ALLIANCE" end
    local ok = pcall(load_world, W, PATH)
    check(TAG .. wname .. ": the file loads", ok)
    if not ok then tally(W); return nil end
    deploy_phases(W); ui(W)
    for i = 1, #(W.enemy_entries or {}) do
      local pr = W.enemy_entries[i]
      if pr ~= nil and pr.unit ~= nil then
        local id = nil
        pcall(function() id = tostring(pr.unit:unique_ui_id()) end)
        pr.unit.is_visible_to_alliance = function(self, a) return true end
        pr.unit.is_currently_flying = function(self) return false end
        local v = sv[id]
        if v ~= nil then pr.unit.strategic_value = function(self) return v end end
      end
    end
    sel_event(W, units[1].uid, true); ui(W); ui(W)
    click(W, "zz_auto_badge_" .. marker); ui(W)
    sel_event(W, units[1].uid, false); ui(W)
    W.conflict = true
    polln(W, 4)
    return W
  end
  local function caster(b, key, o)
    local c = { name = CASTER, uid = b, owns = { key }, melee = false, dist = 60, pos = { 0, 0, 0 }, width = 2,
                men_alive = 1, unit_class = "com" }
    for k, v in pairs(o or {}) do c[k] = v end
    return c
  end
  local function block(uid, name, x, z, o)
    local e = { uid = uid, name = name, melee = false, pos = { x, 0, z }, width = 29.4, men_alive = 120,
                initial_men = 120, unit_class = "inf_mel", dist = 60 }
    for k, v in pairs(o or {}) do e[k] = v end
    return e
  end
  local function single(uid, name, x, z, cls)
    return { uid = uid, name = name, melee = false, pos = { x, 0, z }, width = 6, men_alive = 1, initial_men = 1,
             unit_class = cls, dist = 60 }
  end
  local function ours(uid, z)
    return { uid = uid, name = SW, owns = {}, melee = false, pos = { 0, 0, z }, width = 29.4, men_alive = 120,
             initial_men = 120, unit_class = "inf_mel" }
  end
  local DROPS = { 100, 99, 98, 97, 96, 95, 94, 93, 92, 91, 90, 89, 88, 87, 86, 85, 84, 83, 82, 81, 80 }
  -- name, builder(b) -> units, enemies, sv; marker; key; GREEN casts; RED casts (nil = not RED); target offset
  local WORLDS = {
    { "LS1. Hunting Spear: a Terrorgheist and Grave Guard -> ONE cast at the Terrorgheist (large first)",
      function(b) return { caster(b, HS) }, { single(b + 5, TG, 0, 100, "mon"), block(b + 6, GG, 60, 100) },
        { [tostring(b + 5)] = 2000, [tostring(b + 6)] = 800 } end, "hunting_spear", HS, 1, 0, 5 },
    { "LS2. Hunting Spear: Zombies and Grave Guard, no large -> ONE cast at the Grave Guard (most armour)",
      function(b) return { caster(b, HS) }, { block(b + 5, ZB, 0, 100), block(b + 6, GG, 60, 100) },
        { [tostring(b + 5)] = 75, [tostring(b + 6)] = 800 } end, "hunting_spear", HS, 1, nil, 6 },
    { "LS3. Hunting Spear: our Swordsmen stand on the Terrorgheist -> no cast",
      function(b) return { caster(b, HS), ours(b + 1, 100) }, { single(b + 5, TG, 0, 100, "mon") },
        { [tostring(b + 5)] = 2000 } end, "hunting_spear", HS, 0, nil, nil },
    { "SS1. Dead Eye: a Vampire (900), a Terrorgheist (600), Grave Guard (1500) -> ONE cast at the Vampire",
      function(b) return { caster(b, DE) }, { single(b + 5, VA, 0, 100, "com"), single(b + 6, TG, 60, 100, "mon"),
        block(b + 7, GG, -60, 100) }, { [tostring(b + 5)] = 900, [tostring(b + 6)] = 600, [tostring(b + 7)] = 1500 } end,
      "dead_eye", DE, 1, 0, 5 },
    { "SS2. Focused Shot: a Vampire (1500) and a Terrorgheist (900) -> ONE cast at the Terrorgheist (large first)",
      function(b) return { caster(b, FS) }, { single(b + 5, VA, 0, 100, "com"), single(b + 6, TG, 60, 100, "mon") },
        { [tostring(b + 5)] = 1500, [tostring(b + 6)] = 900 } end, "focused_shot", FS, 1, nil, 6 },
    { "SS3. Dead Eye: the caster is moving -> no cast",
      function(b) return { caster(b, DE, { moving = true }) }, { single(b + 5, VA, 0, 100, "com") },
        { [tostring(b + 5)] = 900 } end, "dead_eye", DE, 0, nil, nil },
    { "IS1. Bolt Storm: Zombies and Grave Guard -> ONE cast at the Grave Guard (value per soldier)",
      function(b) return { caster(b, BS) }, { block(b + 5, ZB, 0, 100), block(b + 6, GG, 60, 100) },
        { [tostring(b + 5)] = 75, [tostring(b + 6)] = 800 } end, "bolt_storm", BS, 1, 0, 6 },
    { "IS2. Bolt Storm: our Swordsmen stand on the Grave Guard -> no cast",
      function(b) return { caster(b, BS), ours(b + 1, 100) }, { block(b + 5, GG, 0, 100) },
        { [tostring(b + 5)] = 800 } end, "bolt_storm", BS, 0, nil, nil },
    { "IS3. Bolt Storm: the caster is in melee -> no cast",
      function(b) return { caster(b, BS, { melee = true }) }, { block(b + 5, GG, 0, 100) },
        { [tostring(b + 5)] = 800 } end, "bolt_storm", BS, 0, nil, nil },
    { "MF1. Crippling Throw: an enemy in melee -> ONE cast at it",
      function(b) return { caster(b, CT) }, { block(b + 5, SW, 0, 100, { melee = true }) }, {} end,
      "crippling_throw", CT, 1, 0, 5 },
    { "MF2. Crippling Throw: a fast enemy (8 m/s) 20 m from us -> ONE cast at it",
      function(b) return { caster(b, CT, { dist = 20 }) }, { block(b + 5, SW, 0, 100, { moving = true, fast_speed = 8 }) },
        {} end, "crippling_throw", CT, 1, nil, 5 },
    { "MF3. Crippling Throw: the caster is in melee -> no cast",
      function(b) return { caster(b, CT, { melee = true }) }, { block(b + 5, SW, 0, 100, { melee = true }) }, {} end,
      "crippling_throw", CT, 0, nil, nil },
    { "MF4. Golden Blowpipe: an enemy in melee 3 m away (min_range 5 m) -> no cast",
      function(b) return { caster(b, GB, { dist = 3 }) }, { block(b + 5, SW, 0, 100, { melee = true }) }, {} end,
      "golden_blowpipe", GB, 0, nil, nil },
    { "MS1. Spear of Kurnous: an enemy in melee -> ONE cast at it",
      function(b) return { caster(b, SK) }, { block(b + 5, SW, 0, 100, { melee = true }) }, {} end,
      "spear_of_kurnous", SK, 1, nil, 5 },
    { "MS2. Spear of Kurnous: shooting handgunners, not in melee -> ONE cast at them",
      function(b) return { caster(b, SK) }, { block(b + 5, GUNS, 0, 100, { ammo_start = 100, ammo_seq = DROPS }) }, {} end,
      "spear_of_kurnous", SK, 1, 0, 5 },
    { "MS3. Spear of Kurnous: idle Swordsmen -> no cast",
      function(b) return { caster(b, SK) }, { block(b + 5, SW, 0, 100) }, {} end, "spear_of_kurnous", SK, 0, nil, nil },
  }
  for _, f in ipairs(FILES) do
    local TAG = f.tag
    for i, w in ipairs(WORLDS) do
      local want = w[5]
      if RED155 then want = w[6] end
      if want ~= nil then
        local b = 18000 + i * 20
        local units, enemies, sv = w[2](b)
        local W = world(w[1], units, enemies, w[3], w[4], f.path, TAG, sv)
        if W ~= nil then
          local got, tid = 0, nil
          for _, x in ipairs(W.fires) do
            if x.key == w[4] then
              got = got + 1
              if tid == nil then pcall(function() tid = tostring(x.target:unique_ui_id()) end) end
            end
          end
          local a = (got == want)
          local ttxt = ""
          if want > 0 and not RED155 and w[7] ~= nil then
            a = a and tid == tostring(b + w[7])
            ttxt = ", target " .. tostring(tid) .. " want " .. tostring(b + w[7])
          end
          check(TAG .. w[1]:sub(1, 3) .. (RED155 and "-RED" or "") .. "a: " .. want .. " cast(s) expected, got " .. got
            .. ttxt, a)
          done(a)
          tally(W)
        end
      end
    end
  end
  if RED155 then
    check("RED CONTROL (harness 155): the pre-156 build has none of the magic missiles - " .. n_ok .. "/" .. n_all,
      n_all == 10 and n_ok == 10)
  else
    check("HARNESS 155: every magic-missile world behaved - " .. n_ok .. "/" .. n_all, n_all == 32 and n_ok == 32)
  end
  print("== HARNESS 155 done: " .. (checks - pre155) .. " checks in this section ==")
end
