def one(s, old, new, n=1):
    assert s.count(old) == n, (old[:70], s.count(old))
    return s.replace(old, new)


def transform(dev, keep_test_switches):
    s = dev
    # R1: the logging section
    a = s.index("local LOG_TAG  = ")
    tail = "\tout(line)\nend\n"
    b = s.index(tail, a) + len(tail)
    assert s[a:b].count("local function log(message)") == 1 and s[a:b].count("io.open") == 1
    s = s[:a] + "local function log(message) end   -- RELEASE: no log at all\n" + s[b:]
    # R2: the read-only periodic dumps
    s = one(s, "\t\tpcall(log_dial_dump)\n", "\t\t-- RELEASE: the dial dump only fed the log\n")
    s = one(s, "\t\tpcall(log_inventory_sweep)\n", "\t\t-- RELEASE: the inventory sweep only fed the log\n")
    s = one(s, "\tpcall(FOURTH.map_tick, tick_count)\n", "\t-- RELEASE: the map probe only fed the log\n")
    s = one(s, "\t\tlog_heartbeat()\n", "\t\t-- RELEASE: the heartbeat only fed the log\n")
    i = s.index("\tif (tick_count % 40) == 0 then\n\t\tlog(\"tick \" .. tostring(tick_count)\n")
    j = s.index("\tend\n", i) + len("\tend\n")
    assert s[i:j].count("armed_states_string()") == 1
    s = s[:i] + "\t-- RELEASE: the 10 s tick line only fed the log\n" + s[j:]
    # R3: the test switches
    names = sorted(set(re.findall(r"\bZZ_AUTO_TEST_[A-Z_]+\b", s)))
    assert len(names) == 7, names   # round 203: + ZZ_AUTO_TEST_NO_FREE_AIM
    if not keep_test_switches:
        s = re.sub(r"\bZZ_AUTO_TEST_[A-Z_]+\b", "nil", s)
    # R6: stand down on every timer when the development build loaded later
    s = one(s, "local function poll()\n", "local function poll()\n\t" + STAND_DOWN)
    s = one(s, "local function ui_tick()\n", "local function ui_tick()\n\t" + STAND_DOWN)
    s = one(s, "bm:repeat_callback(function()\n\tlocal ok, err = pcall(FOURTH.ad_fast_pass)\n",
            "bm:repeat_callback(function()\n\t" + STAND_DOWN + "\tlocal ok, err = pcall(FOURTH.ad_fast_pass)\n")
    # R4: the console functions leave the global table
    for g in DEBUG_GLOBALS:
        assert s.count("\nfunction " + g + "(") == 1, g
    assert len(re.findall(r"\nfunction zz_[a-z_]+\(", s)) == len(DEBUG_GLOBALS)
    s = s.rstrip("\n") + "\n\n-- RELEASE: the console tuning functions are not left in the global table\n" \
        + ", ".join(DEBUG_GLOBALS) + " = " + ", ".join(["nil"] * len(DEBUG_GLOBALS)) + "\n"
    # R5 + the header
    s = HEAD + s
    return s


def check(s, keep_test_switches):
    from lupa import lua51
    err = lua51.LuaRuntime().eval("function(s) local f, e = loadstring(s, '=smart_ability_autocast.lua'); return tostring(e) end")(s)
    assert err == "nil", "the release script does not compile on Lua 5.1: " + err
    assert "\r" not in s
    assert s.count("io.open") == 2, "only the remembered-choices file may be opened (%d io.open)" % s.count("io.open")
    code = "\n".join(line.split("--")[0] for line in s.split("\n"))
    assert "zz_test_deadly_onslaught_log" not in code, "the log file name is still referenced by code"
    for tok in ("pcall(ModLog", "out(line)", "write_to_file(", "pcall(log_dial_dump)", "pcall(log_inventory_sweep)",
                "pcall(FOURTH.map_tick"):
        assert tok not in s, tok
    if not keep_test_switches:
        assert "ZZ_AUTO_TEST_" not in s
    assert s.count("bm:is_multiplayer()") >= 1


def build(keep_test_switches=False, dst=REL_LUA):
    dev = open(DEV, encoding="utf-8", newline="").read()
    s = transform(dev, keep_test_switches)
    check(s, keep_test_switches)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    open(dst, "w", encoding="utf-8", newline="").write(s)
    print("wrote", dst, len(s.encode("utf-8")), "bytes, from the development script md5",
          hashlib.md5(dev.encode("utf-8")).hexdigest())
    return s


class Client:
    def __init__(self):
        from websockets.sync.client import connect
        self.ws = connect("ws://127.0.0.1:45127/ws", max_size=None, open_timeout=15)
        self.n = 1
        self.ws.recv(timeout=15)

    def send(self, cmd):
        i = self.n
        self.n += 1
        self.ws.send(json.dumps({"id": i, "data": cmd}))
        while True:
            m = json.loads(self.ws.recv(timeout=180))
            if m.get("id") == i:
                return m.get("data")


def pack():
    if os.path.exists(OUT_PACK):
        os.remove(OUT_PACK)
    c = Client()
    c.send({"SetGameSelected": ["warhammer_3", False]})
    key = c.send("NewPack")["String"]
    r = c.send({"AddPackedFiles": [key, [f[0].replace("\\", "/") for f in FILES], [{"File": f[1]} for f in FILES], None]})
    print("add:", json.dumps(r)[:120])
    print("type:", c.send({"SetPackFileType": [key, "Mod"]}))
    info = c.send({"GetPackFileDataForTreeView": key})
    container, files = info["ContainerInfoVecRFileInfo"]
    paths = sorted(f["path"] for f in files)
    assert paths == sorted(f[1] for f in FILES), paths
    assert container["pfh_file_type"] == "Mod", container["pfh_file_type"]
    for src, in_pack in FILES:
        raw = bytes(c.send({"GetPackedFileRawData": [key, in_pack]})["VecU8"])
        ok = raw == open(src, "rb").read()
        print("   %-50s %8d bytes  MATCHES SOURCE: %s" % (in_pack, len(raw), ok))
        assert ok, in_pack
    print("save:", json.dumps(c.send({"SavePackAs": [key, OUT_PACK.replace("\\", "/")]}))[:160])
    c.send({"ClosePack": key})
    try:
        c.send("ClientDisconnecting")
    except Exception:
        pass
    data = open(OUT_PACK, "rb").read()
    # (the file list was compared above; the script's own comments still name the development file)
    for tok in (b"zz_probe_", b"C:\\Users", b"C:/Users"):
        assert tok not in data, tok
    for name, src in ((NAME + ".pack", OUT_PACK), (NAME + ".png", PNG)):
        dst = os.path.join(GAME_DATA, name)
        shutil.copy2(src, dst)
        a, b = hashlib.md5(open(src, "rb").read()).hexdigest(), hashlib.md5(open(dst, "rb").read()).hexdigest()
        print("installed %s  md5 %s  IDENTICAL %s  %d bytes" % (dst, b, a == b, os.path.getsize(dst)))
        assert a == b


def main():
    if "--test" in sys.argv:
        build(True, sys.argv[sys.argv.index("--test") + 1])
        return
    build(False)
    if "--pack" in sys.argv:
        pack()


if __name__ == "__main__":
    main()
