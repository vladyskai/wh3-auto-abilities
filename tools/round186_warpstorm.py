#!/usr/bin/env python3
"""Round 186 (user, 2026-11-20, on Warpstorm Scroll: "No need to enforce single-entity. No need to enforce charge, treat
it just as a damage dealer. The slow is not so relevant in this case.").

Warpstorm Scroll leaves enemy_single_drain (single-entity enemies only) for NEW enemy_most_valuable: the most valuable
visible enemy within the entry's 70% bound that its target class allows (here "flying": the game refuses ground
units), any number of models; no clearance (a direct effect on the enemy); the caster standing still only for an
animated cast (blob_still; Warpstorm has none). The pick is the shared shot picker's "value" kind, so the pre-cast
re-check keeps the class and the bound. Rule 10 does not apply: the user ruled the slow irrelevant here.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_shot_tables as GS  # noqa: E402

SRC = r"C:\Users\vlady\Desktop\WH3_mod\mod_source\script\battle\mod\zz_test_deadly_onslaught.lua"
ANN = r"C:\Users\vlady\Desktop\WH3_mod\docs\WH3_auto_ability_annotated.lua"

ENT_OLD = ('\t-- ROUND 184 (rule-shut review row 18)\n'
           '\t{ marker = "warpstorm_scroll", name = "Warpstorm Scroll", trigger = "enemy_single_drain",\n')
ENT_NEW = ('\t-- ROUND 184 (rule-shut review row 18); ROUND 186 (user: "treat it just as a damage dealer"): enemy_most_valuable\n'
           '\t{ marker = "warpstorm_scroll", name = "Warpstorm Scroll", trigger = "enemy_most_valuable",\n')
EVALS = '''
-- ============================================================================
-- ROUND 186 - WARPSTORM SCROLL (user 2026-11-20: "No need to enforce single-entity. No need to enforce charge, treat it
--   just as a damage dealer").
--   enemy_most_valuable: the most valuable visible enemy within the entry's bound that its target class allows, any
--     number of models; no clearance (a direct effect on the enemy); the caster standing still only for an animated
--     cast.
-- ============================================================================
function FOURTH.evaluate_enemy_most_valuable(unit, routing)
	FOURTH.eg_mode = "shot"
	FOURTH.shot_kind = nil
	if routing or not FOURTH.blob_still(unit) then return %NO% end
	local m = FOURTH.blob_map(false)
	local e, s = FOURTH.shot_pick(unit, m, "value", false, true)
	if e == nil then return %NO% end
	FOURTH.shot_take(unit, e, "value", false, true)
	%RET%
end

'''
RET = {True: {"%NO%": "nil", "%RET%": 'return FOURTH.shot_reason(unit, e, "most valuable enemy its rule allows", '
                                       'string.format("value %.0f", s))'},
       False: {"%NO%": "false", "%RET%": "return true"}}
MAP_OLD = "\tally_offering = FOURTH.evaluate_ally_offering,\n"
MAP_NEW = MAP_OLD + "\tenemy_most_valuable = FOURTH.evaluate_enemy_most_valuable,   -- ROUND 186\n"
LBL_OLD = ('\tally_offering = "When armed, fires on the most valuable friendly unit of 30 or more soldiers in melee (no missile '
           'units), cast on it",\n')
LBL_NEW = LBL_OLD + ('\tenemy_most_valuable = "When armed, fires on the most valuable enemy in range that its target rule '
                     'allows",   -- ROUND 186\n')
CARD_OLD = '\tally_offering = "Fires on the most valuable ally of 30+ men in melee; no missile units",\n'
CARD_NEW = CARD_OLD + '\tenemy_most_valuable = "Fires[ when standing still{ANIM},] on the most valuable enemy",   -- ROUND 186\n'
ANCHOR = "FOURTH.evaluators = {\n"
SHOT_GEN = re.compile(r"-- GENERATED by tools/gen_shot_tables\.py from unit_spec_abil, projectiles and the invalid-usage.*?"
                      r"\nFOURTH\.load_shot_table\(\)\n", re.S)


def sub(s, a, b, n=1):
    assert s.count(a) == n, (a[:80], s.count(a))
    return s.replace(a, b)


def main():
    assert "enemy_most_valuable" in GS.FAMILIES, "add enemy_most_valuable to gen_shot_tables.FAMILIES first"
    for path, live in ((SRC, True), (ANN, False)):
        s = open(path, encoding="utf-8", newline="").read()
        assert "evaluate_enemy_most_valuable" not in s
        s = sub(s, ENT_OLD, ENT_NEW)
        s = sub(s, MAP_OLD, MAP_NEW)
        s = sub(s, LBL_OLD, LBL_NEW)
        s = sub(s, CARD_OLD, CARD_NEW)
        ev = EVALS
        for a, b in RET[live].items():
            ev = ev.replace(a, b)
        s = sub(s, ANCHOR, ev + ANCHOR)
        open(path, "w", encoding="utf-8", newline="").write(s)
        print(os.path.basename(path), "Warpstorm Scroll -> enemy_most_valuable")
    src_now = open(SRC, encoding="utf-8").read()
    blk = GS.lua_block(GS.derive(GS.keys_in(src_now)))
    print("SHOT keys:", len(GS.keys_in(src_now)))
    for path in (SRC, ANN):
        s = open(path, encoding="utf-8", newline="").read()
        assert len(SHOT_GEN.findall(s)) == 1
        before = SHOT_GEN.search(s).group(0)
        s = SHOT_GEN.sub(lambda m: blk, s)
        print("SHOT table", "unchanged" if before == blk else "CHANGED")
        open(path, "w", encoding="utf-8", newline="").write(s)


if __name__ == "__main__":
    main()
