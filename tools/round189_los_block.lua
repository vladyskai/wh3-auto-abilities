-- ROUND 189: THE LINE OF FIRE (user ruling 2026-11-21, after the Wulfhart battle where Focused Shot walked Markus
-- 25 m past our own Swordsmen standing across the line: "I would just do the check for terrain on all 35 and units
-- on all 35. Just let's be safe, and if it doesn't fire, that's okay. ... It's better for the mod if it doesn't
-- fire."). The game marks 56 abilities "Requires line of sight to the target" (the ui effect
-- wh3_main_projectile_requires_line_of_sight); 35 of them are ours. For an entry carrying one of those keys an enemy
-- is a target only when the straight line from the caster to it is clear:
--   (1) of EVERY OTHER UNIT on the field, ours and the enemy's (hidden ones too: they stand there all the same). The
--       line may not cross a unit's estimated rectangle (FOURTH.blob_shape, grown by LOS_PAD_M) anywhere between that
--       unit's feet (its position height minus LOS_BELOW_M) and its top (LOS_TOP_M, LOS_LARGE_TOP_M for the
--       generated large set). A flying unit is tested at its own altitude, so a line can pass under it, and a caster
--       on a hill can shoot over units standing below;
--   (2) of the GROUND: bm:get_terrain_height(x, z), sampled every LOS_STEP_M, stays LOS_GROUND_M below the line.
-- The line runs from LOS_EYE_M above the caster to LOS_AIM_M above the target, from where it leaves the caster's own
-- rectangle to where it enters the target's. Before the ground read is trusted it is checked against a unit standing
-- on it (the caster, else the target, whichever reads exactly not flying): the ground under that unit must lie within
-- LOS_CALIB_M of its height.
-- FAIL-CLOSED (the ruling): an unreadable position, flying read or ground read, or a ground read that fails the
-- check, blocks the target. A blocked enemy is only skipped: the picker takes the next best one with a clear line.
-- ASSUMPTIONS (the API has no read for them): the heights; the ground read has no trees, buildings or walls; the unit
-- rectangles are blob_shape's estimate (ordered_width and the game's spacing table).
-- ZZ_AUTO_TEST_NO_LOS is a TEST-ONLY global the harness sets for its older worlds (built before units had places on
-- a ground); the game never defines it.
-- GENERATED by tools/gen_los_keys.py from unit_abilities_to_ui_effects_juncs (the game's 'Requires line of sight to
-- the target' ui effect); the build refuses a pack whose table differs. Do not hand-edit.
@LOS_TEXT@
FOURTH.LOS_KEYS = {}
function FOURTH.load_los()   -- a function, so the loop adds no main-chunk locals
	for k in string.gmatch(FOURTH.LOS_TEXT, "[^;]+") do FOURTH.LOS_KEYS[k] = true end
end
FOURTH.load_los()
FOURTH.LOS_EYE_M = 1.5          -- ASSUMPTION: the caster's launch height above its position
FOURTH.LOS_AIM_M = 1.0          -- ASSUMPTION: the aim point above the target's position
FOURTH.LOS_TOP_M = 2.5          -- ASSUMPTION: a unit's top above its position (man-sized)
FOURTH.LOS_LARGE_TOP_M = 6      -- ASSUMPTION: the same for the generated large set (monsters, cavalry, chariots)
FOURTH.LOS_BELOW_M = 1          -- a unit's feet below its position height
FOURTH.LOS_PAD_M = 1            -- added around every unit's estimated rectangle
FOURTH.LOS_STEP_M = 4           -- the ground is sampled every 4 m along the line
FOURTH.LOS_GROUND_M = 0.5       -- the ground must stay this far below the line
FOURTH.LOS_CALIB_M = 3          -- the ground under a standing unit must lie within 3 m of its height
FOURTH.LOS_LOG_TICKS = 40       -- one log line per entry, caster, enemy and kind of block every 10 s
FOURTH.eg_los = false           -- set per entry by the poll: the entry needs line of sight
FOURTH.eg_caster = nil          -- set per entry by the poll: the caster the shared enemy checks test from
FOURTH.los_cache = {}
FOURTH.los_seen = {}

-- true when the entry carries a key the game marks 'Requires line of sight to the target'
function FOURTH.entry_los(ability)
	for _, k in ipairs(ability.keys or {}) do
		if FOURTH.LOS_KEYS[k] == true then return true end
	end
	return false
end

-- a unit's ui id as text; nil when unreadable
function FOURTH.los_id(u)
	local ok, id = pcall(function() return u:unique_ui_id() end)
	if ok and id ~= nil then return tostring(id) end
	return nil
end

-- x, y (height), z of a unit's centre; nil when unreadable
function FOURTH.los_xyz(u)
	if u == nil then return nil end
	local ok, p = pcall(function() return u:position() end)
	if not ok or p == nil then return nil end
	local ok2, x, y, z = pcall(function() return p:get_x(), p:get_y(), p:get_z() end)
	if not ok2 or type(x) ~= "number" or type(y) ~= "number" or type(z) ~= "number" then return nil end
	return x, y, z
end

-- the ground height at x, z; nil when unreadable
function FOURTH.los_ground(x, z)
	local ok, g = pcall(function() return bm:get_terrain_height(x, z) end)
	if ok and type(g) == "number" then return g end
	return nil
end

-- every living unit on the field, ours and the enemy's: { s = shape, y = height, id, top, side }; built once per tick
function FOURTH.los_units()
	if FOURTH.los_units_tick == tick_count and FOURTH.los_units_list ~= nil then return FOURTH.los_units_list end
	local list = {}
	local function add(u, side)
		if u == nil then return end
		local s = FOURTH.blob_shape(u)
		if s == nil then return end
		local x, y, z = FOURTH.los_xyz(u)
		if y == nil then return end
		local top = FOURTH.LOS_TOP_M
		if s.t ~= nil and FOURTH.class_keys.large[s.t] == true then top = FOURTH.LOS_LARGE_TOP_M end
		list[#list + 1] = { s = s, y = y, id = FOURTH.los_id(u), top = top, side = side }
	end
	for i = 1, #(tracked_units or {}) do add(tracked_units[i] and tracked_units[i].unit, "ours") end
	local ok_c, coll = pcall(function() return bm:get_scriptunits_for_main_enemy_army_to_local_player() end)
	local ok_n, n = false, nil
	if ok_c and coll ~= nil then ok_n, n = pcall(function() return coll:count() end) end
	if ok_n and type(n) == "number" then
		for i = 1, n do
			local e = nil
			pcall(function() e = coll:item(i).unit end)
			add(e, "enemy")
		end
	end
	FOURTH.los_units_list, FOURTH.los_units_tick = list, tick_count
	return list
end

-- the part [t0, t1] (0 = the caster, 1 = the target) of the ground line a -> b that lies inside shape s's rectangle
-- grown by pad metres; nil when the line misses it. Two slabs: across the unit (its right axis, half its width), then
-- along it (its front axis, half its depth).
function FOURTH.los_cross(ax, az, bx, bz, s, pad)
	local px, pz = ax - s.x, az - s.z
	local dx, dz = bx - ax, bz - az
	local t0, t1 = 0, 1
	for k = 1, 2 do
		local p, d, h
		if k == 1 then
			p, d, h = px * s.rx + pz * s.rz, dx * s.rx + dz * s.rz, s.w / 2 + pad
		else
			p, d, h = px * s.fx + pz * s.fz, dx * s.fx + dz * s.fz, s.d / 2 + pad
		end
		if math.abs(d) < 1e-9 then
			if p < -h or p > h then return nil end
		else
			local u0, u1 = (-h - p) / d, (h - p) / d
			if u0 > u1 then u0, u1 = u1, u0 end
			if u0 > t0 then t0 = u0 end
			if u1 < t1 then t1 = u1 end
			if t0 > t1 then return nil end
		end
	end
	return t0, t1
end

-- one log line per battle for each ground-read problem
function FOURTH.los_ground_note(text)
	if FOURTH.los_ground_said == text then return end
	FOURTH.los_ground_said = text
	log("LINE OF FIRE: " .. text .. " - the line-of-sight abilities hold (user ruling 2026-11-21: better not to fire)")
end

-- nil when the line from the caster to the enemy is clear; otherwise the reason and its kind ("unit", "ground",
-- "read")
function FOURTH.los_block(caster, enemy)
	local cx, cy, cz = FOURTH.los_xyz(caster)
	local ex, ey, ez = FOURTH.los_xyz(enemy)
	if cx == nil or ex == nil then return "a position is unreadable", "read" end
	local L = math.sqrt((ex - cx) ^ 2 + (ez - cz) ^ 2)
	if L < 0.5 then return "the caster and the target share a spot", "read" end
	local cid, eid = FOURTH.los_id(caster), FOURTH.los_id(enemy)
	local list = FOURTH.los_units()
	local function same(o, u, id) return o.s.unit == u or (id ~= nil and o.id == id) end
	-- the line's ends: where it leaves the caster's rectangle and where it enters the target's
	local ta, tb = 0, 1
	for i = 1, #list do
		local o = list[i]
		if same(o, caster, cid) then
			local a, b = FOURTH.los_cross(cx, cz, ex, ez, o.s, 0)
			if b ~= nil and b > ta then ta = b end
		elseif same(o, enemy, eid) then
			local a, b = FOURTH.los_cross(cx, cz, ex, ez, o.s, 0)
			if a ~= nil and a < tb then tb = a end
		end
	end
	if ta >= tb then return nil end   -- the two rectangles touch: nothing can stand between them
	local h0, h1 = cy + FOURTH.LOS_EYE_M, ey + FOURTH.LOS_AIM_M
	-- (1) every other unit
	for i = 1, #list do
		local o = list[i]
		if not same(o, caster, cid) and not same(o, enemy, eid) then
			local a, b = FOURTH.los_cross(cx, cz, ex, ez, o.s, FOURTH.LOS_PAD_M)
			if a ~= nil then
				if a < ta then a = ta end
				if b > tb then b = tb end
				if a <= b then
					local ha, hb = h0 + (h1 - h0) * a, h0 + (h1 - h0) * b
					if math.min(ha, hb) <= o.y + o.top and math.max(ha, hb) >= o.y - FOURTH.LOS_BELOW_M then
						return "a unit of " .. o.side .. " (" .. tostring(o.s.t or "?") .. ") stands across the line "
							.. string.format("%.0f", a * L) .. " m out", "unit"
					end
				end
			end
		end
	end
	-- (2) the ground: first checked under a unit standing on it, then sampled along the line
	local ok_c, fc = pcall(function() return caster:is_currently_flying() end)
	local ok_e, fe = pcall(function() return enemy:is_currently_flying() end)
	local rx, ry, rz = nil, nil, nil
	if ok_c and fc == false then
		rx, ry, rz = cx, cy, cz
	elseif ok_e and fe == false then
		rx, ry, rz = ex, ey, ez
	elseif not (ok_c and fc == true and ok_e and fe == true) then
		return "the flying read is unreadable", "read"
	end
	if rx ~= nil then
		local g = FOURTH.los_ground(rx, rz)
		if g == nil then
			FOURTH.los_ground_note("bm:get_terrain_height() is unreadable")
			return "the ground is unreadable", "read"
		end
		if math.abs(g - ry) > FOURTH.LOS_CALIB_M then
			FOURTH.los_ground_note("the ground read is " .. string.format("%.1f", g - ry)
				.. " m off the height of a unit standing on it")
			return "the ground read fails its check", "read"
		end
	end
	local n = math.max(1, math.ceil((tb - ta) * L / FOURTH.LOS_STEP_M))
	for k = 0, n do
		local t = ta + (tb - ta) * k / n
		local g = FOURTH.los_ground(cx + (ex - cx) * t, cz + (ez - cz) * t)
		if g == nil then
			FOURTH.los_ground_note("bm:get_terrain_height() is unreadable")
			return "the ground is unreadable", "read"
		end
		local h = h0 + (h1 - h0) * t
		if g > h - FOURTH.LOS_GROUND_M then
			return "the ground rises across the line " .. string.format("%.0f", t * L) .. " m out ("
				.. string.format("%.1f", g - h) .. " m above it)", "ground"
		end
	end
	return nil
end

-- true unless the current entry needs line of sight, the enemy lies within its bound, and the line to it is blocked
-- (an enemy out of reach is left to the bound test, so the line is drawn only to enemies that could be cast at)
function FOURTH.eg_los_ok(enemy)
	if FOURTH.eg_los ~= true or ZZ_AUTO_TEST_NO_LOS == true then return true end
	local caster = FOURTH.eg_caster
	if caster == nil or enemy == nil then return false end
	if not FOURTH.eg_enemy_within_bound(caster, enemy) then return true end
	local cid, eid = FOURTH.los_id(caster), FOURTH.los_id(enemy)
	local key = (cid ~= nil and eid ~= nil) and (cid .. ">" .. eid) or nil
	local why, kind
	local c = key and FOURTH.los_cache[key]
	if c and c.tick == tick_count then
		why, kind = c.why, c.kind
	else
		why, kind = FOURTH.los_block(caster, enemy)
		if key then FOURTH.los_cache[key] = { tick = tick_count, why = why, kind = kind } end
	end
	if why == nil then return true end
	local lk = tostring(FOURTH.eg_marker) .. ">" .. tostring(key) .. ">" .. tostring(kind)
	local at = FOURTH.los_seen[lk]
	if at == nil or tick_count - at >= FOURTH.LOS_LOG_TICKS then
		FOURTH.los_seen[lk] = tick_count
		log("  " .. tostring(FOURTH.eg_marker) .. " LINE OF FIRE BLOCKED to " .. tostring(FOURTH.type_plain(enemy) or "?")
			.. ": " .. why .. " - not a target")
	end
	return false
end

