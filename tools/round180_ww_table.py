#!/usr/bin/env python3
"""Round 180: regenerate the WW table (the 80% reach for 5 keys; Heaven's Gate closed), in both copies. The block is cut
at the call that starts a line (the round-174 lesson)."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_ww_tables as G  # noqa: E402

SRC = r"C:\Users\vlady\Desktop\WH3_mod\mod_source\script\battle\mod\zz_test_deadly_onslaught.lua"
ANN = r"C:\Users\vlady\Desktop\WH3_mod\docs\WH3_auto_ability_annotated.lua"
HEAD = "-- GENERATED by tools/gen_ww_tables.py from unit_spec_abil and battle_vortexs"
TAIL = "\nFOURTH.load_ww_table()\n"
live = open(SRC, encoding="utf-8").read()
kf = G.keys_in(live)
block = G.lua_block(G.derive(kf))
print(len(kf), "WW keys")
for path in (SRC, ANN):
    s = open(path, encoding="utf-8", newline="").read()
    assert s.count(HEAD) == 1
    i = s.index(HEAD)
    j = s.index(TAIL, i) + len(TAIL)
    s = s[:i] + block + s[j:]
    assert s.count("function FOURTH.load_ww_table()") == 1 and s.count(TAIL) == 1
    open(path, "w", encoding="utf-8", newline="").write(s)
    print(path[-30:], "WW regenerated")
