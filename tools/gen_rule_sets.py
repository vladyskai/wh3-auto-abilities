#!/usr/bin/env python3
"""Round 180: two unit sets for the game's ally target rules (special_ability_to_invalid_target_flags), from the game's
own tables (user approval 2026-11-18, score-3 review rows 107 and 128 of docs\\WH3_score3_review_2026-11-18.md).

lizard (unit_is_not_a_lizard_unit, Cold-Blooded): land_units whose key carries the Lizardmen culture prefix '_lzd_'
    (user ruling 2026-11-18: "Row 128 set A"). ASSUMPTION: the engine's flag covers every Lizardmen unit; the data has
    no lizard attribute. A wider set can only mean a cast the game refuses, never a valid target skipped.
tiger (unit_is_not_tiger_warrior, Mantra of Invigoration): land_units whose attribute_group carries the game's
    'tiger_warrior' attribute (unit_attributes_to_groups_junctions, gamedata/wh3/unit_attr_groups.tsv), the method of
    tools/gen_squig_keys.py.
derive_lizard() / derive_tiger() are imported by the round-180 patch (to embed the text) and by the builder (to refuse a
pack whose table differs from the game data)."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_unit_size_keys import rows  # noqa: E402


def derive_lizard():
    return {r["key"] for r in rows("land_units.tsv") if "_lzd_" in r["key"]}


def derive_tiger():
    groups = {r["attribute_group"] for r in rows("unit_attr_groups.tsv") if r.get("attribute") == "tiger_warrior"}
    return {r["key"] for r in rows("land_units.tsv") if r.get("attribute_group", "") in groups}


def derive_moulder():
    """ROUND 192 (user 2026-11-21: "do it"): the game's 'moulder_monster' attribute (28 land units: Rat Ogres, Hell Pit
    Abominations, Brood Horrors, Wolf Rats, Stormfiends, the Moulder lords and heroes on such mounts). The flag on
    Shock Collar and Remouldered is named unit_is_moulder_monster, but its own text (special_ability_invalid_usage_flags
    loc, flag_description) reads 'Unit is not a Clan Moulder Monster': the target must BE one."""
    groups = {r["attribute_group"] for r in rows("unit_attr_groups.tsv") if r.get("attribute") == "moulder_monster"}
    return {r["key"] for r in rows("land_units.tsv") if r.get("attribute_group", "") in groups}


def text(keys):
    return ";".join(sorted(keys))


def lua_block_180():
    """The round-180 block (lizard and tiger only): round192_moulder.py replaces it with lua_block()."""
    return ("-- GENERATED by tools/gen_rule_sets.py from land_units and unit_attributes_to_groups_junctions (the game's ally\n"
            "-- target rules unit_is_not_a_lizard_unit: the '_lzd_' units, user ruling 'set A'; unit_is_not_tiger_warrior:\n"
            "-- the 'tiger_warrior' attribute); the build refuses a pack whose tables differ. Do not hand-edit.\n"
            "FOURTH.LIZARD_TEXT = \"%s\"\n"
            "FOURTH.TIGER_TEXT = \"%s\"\n"
            "FOURTH.class_keys.lizard = {}\n"
            "FOURTH.class_keys.tiger = {}\n"
            "function FOURTH.load_rule_sets()   -- a function, so the loops add no main-chunk locals\n"
            "\tfor k in string.gmatch(FOURTH.LIZARD_TEXT, \"[^;]+\") do FOURTH.class_keys.lizard[k] = true end\n"
            "\tfor k in string.gmatch(FOURTH.TIGER_TEXT, \"[^;]+\") do FOURTH.class_keys.tiger[k] = true end\n"
            "end\n"
            "FOURTH.load_rule_sets()\n" % (text(derive_lizard()), text(derive_tiger())))


