#!/usr/bin/env python3
"""Round 171: regenerate every GENERATED table that is keyed on the mod's own key list (nine keys closed, two entries
split), in both copies. Each table is rebuilt by its own generator and replaced only when it differs; the report says
which moved. Tables: RECHARGE (gen_recharge_keys), the wind-up table (cast_gate.wind_up_s, the round-160 rule), ANIM
(gen_anim_keys), USAGE and ATARGET (gen_usage_keys), RISKY (gen_risky_keys)."""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gamedata_paths as GP  # noqa: E402
import gen_anim_keys as GA  # noqa: E402
import gen_recharge_keys as GR  # noqa: E402
import gen_risky_keys as GK  # noqa: E402
import gen_usage_keys as GU  # noqa: E402

SRC = r"C:\Users\vlady\Desktop\WH3_mod\mod_source\script\battle\mod\zz_test_deadly_onslaught.lua"
ANN = r"C:\Users\vlady\Desktop\WH3_mod\docs\WH3_auto_ability_annotated.lua"


def replace_line(s, prefix, new_value, label, report):
    i = s.index(prefix)
    j = s.index('"\n', i + len(prefix))
    old = s[i + len(prefix):j]
    if old != new_value:
        report.append("%s: changed (%d -> %d chars)" % (label, len(old), len(new_value)))
        s = s[:i + len(prefix)] + new_value + s[j:]
    else:
        report.append("%s: unchanged" % label)
    return s


def wind_up(script_txt):
    keys = set()
    for m in re.finditer(r"\t\tkeys = \{(.*?)\}", script_txt, re.S):
        keys.update(re.findall(r'"([^"]+)"', m.group(1)))
    wu = {}
    with open(os.path.join(GP.GAMEDATA, "unit_spec_abil.tsv"), encoding="utf-8-sig") as f:
        h = f.readline().rstrip("\n").split("\t")
        f.readline()
        for line in f:
            d = dict(zip(h, line.rstrip("\n").split("\t")))
            if d["key"] in keys and float(d["wind_up_time"] or 0) > 0:
                wu[d["key"]] = float(d["wind_up_time"])
    return keys, wu


def main():
    live = open(SRC, encoding="utf-8").read()
    anim = GA.text(GA.derive(live))
    usage = GU.text(GU.derive(live))
    atarget = GU.target_text(GU.derive_target(live))
    risky = GK.text(GK.derive(live))
    keys, wu = wind_up(live)
    print("mod keys:", len(keys), "with a wind-up:", len(wu))
    for path in (SRC, ANN):
        s = open(path, encoding="utf-8", newline="").read()
        rep = []
        s = replace_line(s, 'FOURTH.ANIM_TEXT = "', anim, "ANIM", rep)
        s = replace_line(s, 'FOURTH.USAGE_TEXT = "', usage, "USAGE", rep)
        s = replace_line(s, 'FOURTH.ATARGET_TEXT = "', atarget, "ATARGET", rep)
        s = replace_line(s, 'FOURTH.RISKY_TEXT = "', risky, "RISKY", rep)
        # the recharge table: the generator's whole block
        new_blk = GR.lua_block(GR.derive())
        if new_blk in s:
            rep.append("RECHARGE: unchanged")
        else:
            m = re.search(r"-- GENERATED by tools/gen_recharge_keys\.py.*?\nFOURTH\.load_recharge\(\)\n", s, re.S)
            assert m, "the recharge block was not found"
            s = s[:m.start()] + new_blk + s[m.end():]
            assert new_blk in s
            rep.append("RECHARGE: changed")
        # the wind-up table: drop the rows of keys the mod no longer carries
        blk_i = s.index("\twind_up_s = {")
        blk_j = s.index("\n\t}", blk_i)
        blk = s[blk_i:blk_j]
        rows = re.findall(r'\n\t\t\["([^"]+)"\] = ([\d.]+),', blk)
        gone = [k for k, _ in rows if k not in wu]
        for k in gone:
            blk = re.sub(r'\n\t\t\["%s"\] = [\d.]+,[^\n]*' % re.escape(k), "", blk)
        tab = dict((k, float(v)) for k, v in re.findall(r'\["([^"]+)"\] = ([\d.]+)', blk))
        assert tab == wu, (set(tab) ^ set(wu))
        s = s[:blk_i] + blk + s[blk_j:]
        rep.append("WIND-UP: %d row(s) removed %s" % (len(gone), gone))
        open(path, "w", encoding="utf-8", newline="").write(s)
        print(os.path.basename(path), "|", "; ".join(rep))


if __name__ == "__main__":
    main()
