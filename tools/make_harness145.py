#!/usr/bin/env python3
"""Build harness145.lua from harness144.lua for round 146 (the blob trigger: 77 exploding enemy-unit attacks). Older
harnesses are never edited.

Pin rebases (code lines only; a rule with a guard only touches lines holding the guard):
  entries 722 -> 799, keys 777 -> 854 (77 entries / 77 keys), full-table iterations 1444 -> 1598,
  multi-use charge-gate keys 176 -> 246 (+70), wind-up keys 169 -> 235 (+66), range_real fields 217 -> 294 (+77),
  target classes 24 -> 26 (two not_flying);
  the round-145 "map code casts nothing" span now ends at the round-146 block (the blob code below it casts by design);
  the tooltip mirror gains the enemy_blob wording.
"""
import os
import re

SRC = r"C:\Users\vlady\Desktop\WH3_mod\mod_source\releases\20261113_map_probe_harness144\harness144.lua"
DST = r"C:\Users\vlady\Desktop\WH3_mod\mod_source\releases\20261113_blob_trigger_harness145\harness145.lua"

BANNER = """-- ============================================================================
-- HARNESS 145 - ROUND 146: THE BLOB TRIGGER (77 exploding enemy-unit attacks).
--   enemy_blob: the best SAFE visible enemy infantry unit whose blast reaches
--   half a packed block's worth of soldiers; nobody of ours within blast + 10 m.
--   Edited vs harness144: this banner, the pin rebases listed in
--   tools/make_harness145.py, the tooltip mirror, run_h145 and its call.
--   RED control: H145_LIVE / H145_ANN on docs/backups/round146/pre146_*.lua.
-- ============================================================================
"""

SECTION = r'''
-- ============================================================================
-- HARNESS 145 (round 146): THE BLOB TRIGGER.
--   Fireball (blast 5 m, line 17 soldiers, bound 210 m); Dire Spirit Bear
--   (blast 10 m, line 66, bound 105 m). The caster stands 100 m from the enemy.
--   FB1 a full Swordsmen block (120 men, 29.4 m wide -> 6 ranks, 9.6 m deep,
--   about 33 soldiers in 5 m): ONE cast at it. FB2 20 men in one thin rank: none.
--   FB3 our Swordsmen 10 m from its rear edge (blast + 10 = 15 m): none.
--   FB4 our Swordsmen 40 m away: ONE cast. FB5 the enemy is NOT visible: none.
--   FB6 the enemy is a large monster the engine calls infantry (Devils): none.
--   FB7 no alliance read (bm:get_player_alliance missing): none (fail-closed).
--   FB8 two blocks, the thin one nearer: the cast goes at the DENSE one.
--   SB1 a full block (about 91 soldiers in 10 m): ONE cast. SB2 80 men (4 ranks,
--   about 33 in 10 m): none.
--   RED (pre-146 = round 145): FB1 and SB1 cast nothing.
-- ============================================================================
function run_h145()
  local L145 = os.getenv("H145_LIVE") or LIVE
  local A145 = os.getenv("H145_ANN") or ANN
  local RED145 = (os.getenv("H145_LIVE") ~= nil) or (os.getenv("H145_ANN") ~= nil)
  local FB = "wh_main_spell_bound_fireball"
  local SB = "wh3_dlc24_lord_abilities_spirit_bear_upgrade"
  local CASTER = "wh2_dlc13_emp_cha_huntsmen_general_0"
  local SW = "wh_main_emp_inf_swordsmen"
  local DEV = "wh_dlc04_vmp_mon_devils_swartzhafen_0"
  local pre145 = checks
  local function cp(s, tok)
    local n, at = 0, 1
    while true do
      local i = raw_find(s, tok, at, true)
      if i == nil then return n end
      n = n + 1; at = i + #tok
    end
  end

  print("== HARNESS 145 - section 0zr: the round-146 tokens ==")
  if not RED145 then
    for _, f in ipairs({ { name = "live", path = L145 }, { name = "ann", path = A145 } }) do
      local s = read_file(f.path)
      check("0zr " .. f.name .. ": 799 entries, 77 on enemy_blob, the user's settings, the generated tables, the re-check",
        cp(s, "\t{ marker = ") == 799 and cp(s, 'trigger = "enemy_blob"') == 77
        and raw_find(s, "FOURTH.BLOB_MARGIN_M = 10 ", 1, true) ~= nil
        and raw_find(s, "FOURTH.BLOB_FRACTION = 0.5 ", 1, true) ~= nil
        and raw_find(s, "FOURTH.PACKED_M2 = 2.368\n", 1, true) ~= nil
        and raw_find(s, "-- GENERATED by tools/gen_blob_tables.py", 1, true) ~= nil
        and raw_find(s, "wh_main_spell_bound_fireball=5;", 1, true) ~= nil
        and raw_find(s, 'elseif eg_mode_now == "blob" then', 1, true) ~= nil
        and raw_find(s, "enemy_blob = FOURTH.evaluate_enemy_blob,", 1, true) ~= nil
        and raw_find(s, "wh3_dlc26_character_abilities_dead_eye", 1, true) == nil
        and raw_find(s, "wh2_dlc13_lord_abilities_kill_shot", 1, true) == nil
        and raw_find(s, "FOURTH.ENEMY_CAST_R250 = 175", 1, true) ~= nil
        and raw_find(s, "FOURTH.ENEMY_CAST_R600 = 420", 1, true) ~= nil)
    end
  end

  local FILES = { { path = A145, tag = "[annotated] " }, { path = L145, tag = "[live] " } }
  local n_ok, n_all = 0, 0
  local function done(ok) n_all = n_all + 1; if ok then n_ok = n_ok + 1 end end
  -- opts: alliance (default true), vis (uid -> bool, default true)
  local function world(wname, units, enemies, arm, key, PATH, TAG, opts)
    opts = opts or {}
    local cards = {}
    for _, d in ipairs(units) do cards[#cards + 1] = { id = tostring(d.uid), state = "active", vis = true } end
    local W = make_world({ can_perform = true, units = units, enemies = enemies, cards = cards,
      bar = { { id = "b1", key = key } } })
    print("== " .. TAG .. wname .. " ==")
    if opts.alliance ~= false then
      W.bm.get_player_alliance = function() return "OUR_ALLIANCE" end
    end
    local ok = pcall(load_world, W, PATH)
    check(TAG .. wname .. ": the file loads", ok)
    if not ok then tally(W); return nil end
    deploy_phases(W); ui(W)
    for i = 1, #(W.enemy_entries or {}) do
      local pr = W.enemy_entries[i]
      if pr ~= nil and pr.unit ~= nil then
        local id = nil
        pcall(function() id = tostring(pr.unit:unique_ui_id()) end)
        local v = true
        if opts.vis ~= nil and opts.vis[id] ~= nil then v = opts.vis[id] end
        pr.unit.is_visible_to_alliance = function(self, a) return v end
      end
    end
    sel_event(W, arm[1], true); ui(W); ui(W)
    click(W, "zz_auto_badge_" .. arm[2]); ui(W)
    sel_event(W, arm[1], false); ui(W)
    W.conflict = true
    polln(W, 4)
    return W
  end
  local function caster(b, key)
    return { name = CASTER, uid = b, owns = { key }, melee = false, dist = 100, pos = { 0, 0, 0 }, width = 2,
             men_alive = 1, unit_class = "com" }
  end
  local function block(uid, name, men, z, x)
    return { uid = uid, name = name, melee = false, pos = { x or 0, 0, z }, width = 29.4, men_alive = men,
             initial_men = 120, unit_class = "inf_mel" }
  end
  local function ours(uid, z)
    return { uid = uid, name = SW, owns = {}, melee = false, pos = { 0, 0, z }, width = 29.4, men_alive = 120,
             initial_men = 120, unit_class = "inf_mel" }
  end
  -- name, builder(b) -> units, enemies, opts; marker; key; GREEN casts; RED (nil = not RED); target uid offset
  local WORLDS = {
    { "FB1. Fireball: a full Swordsmen block 100 m away -> ONE cast at it",
      function(b) return { caster(b, FB) }, { block(b + 5, SW, 120, 150) } end, "spell_bound_fireball", FB, 1, 0, 5 },
    { "FB2. Fireball: 20 men in one thin rank -> no cast",
      function(b) return { caster(b, FB) }, { block(b + 5, SW, 20, 150) } end, "spell_bound_fireball", FB, 0, nil, nil },
    { "FB3. Fireball: our Swordsmen 10 m behind its rear edge (needs more than 15 m) -> no cast",
      function(b) return { caster(b, FB), ours(b + 1, 130.0) }, { block(b + 5, SW, 120, 150) } end,
      "spell_bound_fireball", FB, 0, nil, nil },
    { "FB4. Fireball: our Swordsmen 40 m away -> ONE cast",
      function(b) return { caster(b, FB), ours(b + 1, 100.0) }, { block(b + 5, SW, 120, 150) } end,
      "spell_bound_fireball", FB, 1, nil, 5 },
    { "FB5. Fireball: the block is NOT visible to us -> no cast",
      function(b) return { caster(b, FB) }, { block(b + 5, SW, 120, 150) }, { vis = { [tostring(b + 5)] = false } } end,
      "spell_bound_fireball", FB, 0, nil, nil },
    { "FB6. Fireball: a large monster the engine calls infantry (Devils) -> no cast",
      function(b) return { caster(b, FB) }, { block(b + 5, DEV, 120, 150) } end, "spell_bound_fireball", FB, 0, nil, nil },
    { "FB7. Fireball: no alliance read -> no cast (fail-closed)",
      function(b) return { caster(b, FB) }, { block(b + 5, SW, 120, 150) }, { alliance = false } end,
      "spell_bound_fireball", FB, 0, nil, nil },
    { "FB8. Fireball: a thin block nearer, a full block further -> the cast goes at the FULL block",
      function(b) return { caster(b, FB) }, { block(b + 5, SW, 20, 120, -60), block(b + 6, SW, 120, 170, 60) } end,
      "spell_bound_fireball", FB, 1, nil, 6 },
    { "SB1. Dire Spirit Bear: a full block -> ONE cast at it",
      function(b) return { caster(b, SB) }, { block(b + 5, SW, 120, 150) } end, "lord_abilities_spirit_bear_upgrade", SB, 1, 0, 5 },
    { "SB2. Dire Spirit Bear: an 80-man block (4 ranks) -> no cast",
      function(b) return { caster(b, SB) }, { block(b + 5, SW, 80, 150) } end, "lord_abilities_spirit_bear_upgrade", SB, 0, nil, nil },
  }
  for _, f in ipairs(FILES) do
    local TAG = f.tag
    for i, w in ipairs(WORLDS) do
      local want = w[5]
      if RED145 then want = w[6] end
      if want ~= nil then
        local base = 16000 + i * 20
        local units, enemies, opts = w[2](base)
        local W = world(w[1], units, enemies, { base, w[3] }, w[4], f.path, TAG, opts)
        if W ~= nil then
          local got, last = 0, nil
          for _, x in ipairs(W.fires) do if x.key == w[4] then got = got + 1; last = x end end
          local a = (got == want)
          if a and not RED145 and got >= 1 and w[7] ~= nil then
            local tid = nil
            if last.target ~= nil then pcall(function() tid = tostring(last.target:unique_ui_id()) end) end
            a = (tid == tostring(base + w[7]))
          end
          check(TAG .. w[1]:sub(1, 3) .. (RED145 and "-RED" or "") .. "a: " .. tostring(want) .. " cast(s) expected, got "
            .. got, a)
          done(a)
          if TAG == "[live] " and got >= 1 and not RED145 then
            local seen = false
            for _, l in ipairs(W.log_lines or {}) do
              if raw_find(l, "infantry blob (targeting", 1, true) ~= nil then seen = true end
            end
            check(TAG .. w[1]:sub(1, 3) .. "b: the reason names the blob, the soldier count and the line", seen)
          end
          tally(W)
        end
      end
    end
  end
  if RED145 then
    check("RED CONTROL (harness 145): the pre-146 build has no blob trigger - " .. n_ok .. "/" .. n_all,
      n_all == 4 and n_ok == 4)
  else
    check("HARNESS 145: every blob world behaved - " .. n_ok .. "/" .. n_all, n_all == 20 and n_ok == 20)
  end
  print("== HARNESS 145 done: " .. (checks - pre145) .. " checks in this section ==")
end
'''

PIN_RULES = [
    (r"== 722\b", "== 799", None),
    (r"== 777\b", "== 854", None),
    (r"it == 1444\b", "it == 1598", None),
    (r"entries = 722, keys = 777", "entries = 799, keys = 854", None),
    (r"want 722\b", "want 799", None),
    (r"FULL 722-entry table", "FULL 799-entry table", None),
    (r"722 abilities per pass", "799 abilities per pass", None),
    (r"table of 722 after round 144", "table of 799 after round 146", None),
    (r"\(12 air-drop entries of 722\)", "(12 air-drop entries of 799)", None),
    (r"\(RED_MODE and 0 or 176\)", "(RED_MODE and 0 or 246)", None),
    (r"nkeys == 169\b", "nkeys == 235", None),
    (r"== 217\)", "== 294)", "range_real = \")"),
    (r"\(EXP\.sum and 217 or 96\)", "(EXP.sum and 294 or 96)", None),
    (r"== 24\)", "== 26)", "target_class = \")"),
]
src = open(SRC, encoding="utf-8").read()
lines = src.split("\n")
changed, hits = [], {a: 0 for a, _, _ in PIN_RULES}
for i, ln in enumerate(lines):
    if ln.lstrip().startswith("--"):
        continue
    new = ln
    for a, b, guard in PIN_RULES:
        if guard is not None and guard not in new:
            continue
        new2, n = re.subn(a, b, new)
        if n:
            hits[a] += n
            new = new2
    if new != ln:
        changed.append(i + 1)
        lines[i] = new
src = "\n".join(lines)
print("count-pin lines rebased:", len(changed), "| rules with no hit:", [a for a, v in hits.items() if v == 0])
SPAN_OLD = '    local b = raw_find(live, "FOURTH.evaluators = {", 1, true)\n'
SPAN_NEW = '    local b = raw_find(live, "-- ROUND 146 - THE BLOB TRIGGER", 1, true)   -- ROUND 146: the blob code below casts by design\n'
assert src.count(SPAN_OLD) == 1, src.count(SPAN_OLD)
src = src.replace(SPAN_OLD, SPAN_NEW)
TIP_OLD = '    enemy_wavering = "When armed, fires on the closest wavering enemy in range",\n'
TIP_NEW = TIP_OLD + ('    enemy_blob = "When armed, fires at the densest enemy infantry in range when the blast hits enough '
                     'soldiers and none of ours are near",\n')
assert src.count(TIP_OLD) == 1, src.count(TIP_OLD)
src = src.replace(TIP_OLD, TIP_NEW)
RUNNER_ANCHOR = "\n-- THE RUNNER. The air-drop sections always run;"
assert src.count(RUNNER_ANCHOR) == 1
src = src.replace(RUNNER_ANCHOR, "\n" + SECTION + RUNNER_ANCHOR)
CALL = "run_h143()\nrun_h144()\n"
assert src.count(CALL) == 1, src.count(CALL)
src = src.replace(CALL, CALL + "run_h145()\n")
src = BANNER + src
assert "\u2014" not in BANNER + SECTION
os.makedirs(os.path.dirname(DST), exist_ok=True)
open(DST, "w", encoding="utf-8", newline="\n").write(src)
print("wrote", DST, len(src), "bytes")
