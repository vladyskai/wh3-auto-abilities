#!/usr/bin/env python3
"""Derive the UNDEAD land_units key set from the game's own tables (round 138, Eternal Gaze's undead_unit flag).

undead: land_units.attribute_group carries the unit attribute "undead"
(unit_attributes_to_groups_junctions_tables, extracted live as gamedata/wh3/unit_attr_groups.tsv).
derive() is imported by the round-138 patch (to embed the Lua table) and by the builder (to refuse a pack
whose table differs from the game data)."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_unit_size_keys import rows  # noqa: E402


def derive():
    groups = {r["attribute_group"] for r in rows("unit_attr_groups.tsv") if r.get("attribute") == "undead"}
    return {r["key"] for r in rows("land_units.tsv") if r.get("attribute_group", "") in groups}


def lua_block(undead):
    out = ["-- GENERATED by tools/gen_undead_keys.py from unit_attributes_to_groups_junctions and land_units",
           "-- (round 138); the build refuses a pack whose table differs from the game data.",
           "FOURTH.class_keys.undead = {"]
    out += ['\t["%s"] = true,' % k for k in sorted(undead)]
    out += ["}"]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    u = derive()
    print("undead", len(u))
