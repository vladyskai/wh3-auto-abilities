FAMILIES = ("enemy_wave", "enemy_wander",
            "enemy_strike", "ally_blast",   # ROUND 163: Siegebreaker (kind 4), Arcane Vassal (its radius)
            "enemy_wave_charge", "enemy_cone", "enemy_sweep")   # ROUND 164: kinds 1 (charge arm), 5, 7


def nomelee(keys):
    """ROUND 164: the keys the game refuses while their caster is in melee (special_ability_to_invalid_usage_flags:
    engaged_in_melee), for the WW families' caster gate"""
    flagged = {r["special_ability"] for r in tsv("special_ability_to_invalid_usage_flags_tables.tsv")
               if r["invalid_usage_flag"] == "engaged_in_melee"}
    return sorted(k for k in keys if k in flagged)


def nomelee_block(keys):
    return ("-- GENERATED by tools/gen_ww_tables.py from special_ability_to_invalid_usage_flags (engaged_in_melee: the game\n"
            "-- refuses the cast while the caster fights); the build refuses a pack whose list differs. Do not hand-edit.\n"
            "FOURTH.WW_NOMELEE_TEXT = \"%s\"\n"
            "FOURTH.WW_NOMELEE = {}\n"
            "function FOURTH.load_ww_nomelee()\n"
            "\tfor k in string.gmatch(FOURTH.WW_NOMELEE_TEXT, \"[^;]+\") do FOURTH.WW_NOMELEE[k] = true end\n"
            "end\n"
            "FOURTH.load_ww_nomelee()\n" % ";".join(nomelee(keys)))
RUNS = 4000
# ROUND 180 (user, 2026-11-18: "Row 91-96 implement as in the doc"): the 80% simulated reach for the keys whose 95%
# buffer left almost no window inside their 70% bound (review rows 91, 93, 95, 96). A straight path (no turn) keeps its
# whole length whatever the share (Lamprey's Bite).
Q80 = {"wh2_dlc09_lord_abilities_sand_storm", "wh3_dlc24_unit_abilities_lampreys_bite",
       "wh3_dlc25_spell_bound_fire_the_burning_head", "wh3_dlc29_spell_bound_fire_skull_of_flaming_death",
       "wh2_dlc10_item_bound_arnizipals_black_horror"}


def tsv(name):
    with open(os.path.join(GP.GAMEDATA, name), encoding="utf-8-sig") as f:
        h = f.readline().rstrip("\n").split("\t")
        f.readline()
        for line in f:
            yield dict(zip(h, line.rstrip("\n").split("\t")))


def keys_in(script_txt):
    out = {}
    for m in re.finditer(r'trigger = "(%s)",\n\t\tbadge = "[^"]+",\n\t\tkeys = \{ "([^"]+)" \}' % "|".join(FAMILIES),
                         script_txt):
        out[m.group(2)] = m.group(1)
    return out


def drift95(v, key, wave):
    """the 95% drift of one vortex row: sideways (wave) or from the start (wanderer), the wider of two readings"""
    spd, dur = float(v["movement_speed"] or 0), float(v["duration"] or 0)
    ang, freq = float(v["change_max_angle"] or 0), float(v["move_change_freq"] or 0)
    if spd <= 0 or dur <= 0:
        return 0.0
    if freq <= 0 or ang <= 0:
        # no turn: a wave stays on its line; a wanderer goes straight out (heading unknown) for its whole path
        return 0.0 if wave else spd * dur
    best = 0.0
    for lim in (ang, ang / 2.0):
        rng = random.Random("%s/%g" % (key, lim))
        vals = []
        for _ in range(RUNS):
            x = z = h = t = 0.0
            mx = 0.0
            while t < dur - 1e-9:
                leg = min(freq, dur - t)
                x += spd * leg * math.cos(h)
                z += spd * leg * math.sin(h)
                t += leg
                mx = max(mx, abs(z) if wave else math.hypot(x, z))
                if lim >= 360:
                    h = rng.uniform(0.0, 2.0 * math.pi)
                else:
                    h += math.radians(rng.uniform(-lim, lim))
            vals.append(mx)
        vals.sort()
        best = max(best, vals[int((0.80 if key in Q80 else 0.95) * RUNS)])
    return best


def bombardment(usa_row):
    """ROUND 163: an ability's bombardment reach and friendly fire: (radius_spread + the projectile's blast radius,
    hits_allies), or None when it has no bombardment. projectile_bombardments -> projectiles -> projectiles_explosions."""
    b = usa_row.get("bombardment", "")
    if not b:
        return None
    bomb = {r["bombardment_key"]: r for r in tsv("projectile_bombardments.tsv")}[b]
    prj = {r["key"]: r for r in tsv("projectiles.tsv")}[bomb["projectile_type"]]
    exp = {r["key"]: r for r in tsv("projectiles_explosions.tsv")}.get(prj.get("explosion_type", ""), {})
    reach = float(bomb["radius_spread"] or 0) + float(exp.get("detonation_radius") or 0)
    allies = 1 if (prj.get("can_damage_allies") == "true" or exp.get("affects_allies") == "true") else 0
    return reach, allies


def derive(key_fams):
    usa = {r["key"]: r for r in tsv("unit_spec_abil.tsv")}
    vx = {r["vortex_key"]: r for r in tsv("battle_vortexs.tsv")}
    out = {}
    for k, fam in sorted(key_fams.items()):
        rows = GV.chain(vx, usa[k]["vortex"])
        bomb = bombardment(usa[k])
        assert rows or bomb, "%s has no vortex and no bombardment" % k
        # ROUND 164: enemy_wave_charge (Tidecall, Wind Blast) is a wave aimed at a charging enemy; enemy_cone (the breaths
        # from the caster's front) drifts like a wave
        wave = fam in ("enemy_wave", "enemy_wave_charge")
        cone = (fam == "enemy_cone")
        if rows:
            v = rows[0]
            # a wave must launch from the target's near edge; a wanderer may too (The Ruination of Cities: three spokes
            # from the near edge, offset 0, no turn, so its buffer is its whole path)
            assert (not wave) or v["launch_source"] == "target_near_edge", "%s: wave launched from %s" % (k, v["launch_source"])
            assert (not cone) or v["launch_source"] == "activator_front", "%s: cone launched from %s" % (k, v["launch_source"])
            r = max(max(float(x["start_radius"] or 0), float(x["goal_radius"] or 0)) for x in rows)
            path = float(v["movement_speed"] or 0) * float(v["duration"] or 0)
            off = float(v["launch_source_offset"] or 0)
            buf = int(math.ceil(drift95(v, k, wave or cone) - 1e-9))
            allies = 1 if any(x["affects_allies"] == "true" for x in rows) else 0
            kind = 1 if wave else (3 if v["launch_source"] == "target_near_edge" else 2)
            if cone:
                kind = 5   # ROUND 164: a breath from the caster's front: the zone runs from the caster through the target
            elif fam == "enemy_wander" and v["launch_source"] == "activator_front":
                kind = 6   # ROUND 164: a wanderer released at the caster (Da Boss' Loons): the safety ring is the caster's
            elif fam == "enemy_sweep":
                # ROUND 164: a melee sweep from the caster onto an adjacent enemy: its reach from the caster is the
                # ability's range + the launch offset + the travel + the radius
                assert v["launch_source"] == "target_from_owner_wait_for_orientation", (k, v["launch_source"])
                r = float(usa[k]["target_intercept_range"] or 0) + off + path + r
                kind, buf = 7, 0
        else:
            assert not wave, k
            r, path, off, buf, allies, kind = 0.0, 0.0, 0.0, 0, 0, 2
        if bomb is not None:
            # ROUND 163: a bombardment's own reach (Magma Storm: 60 m spread + 5 m blasts; Hell Hammer: a 14 m blast).
            # A wave's corridor radius takes it; a static area or wanderer keeps its vortex radius for scoring the
            # target and adds the extra reach to its safety buffer (with no vortex, the reach IS the radius).
            if wave or not rows:
                r = max(r, bomb[0])
            else:
                buf = max(buf, int(math.ceil(bomb[0] - r - 1e-9)))
            allies = max(allies, bomb[1])
        ground = 1 if (usa[k]["target_enemies"] != "true" and usa[k]["target_ground"] == "true") else 0
        if fam == "enemy_strike":
            # ROUND 163: a single strike on the ground under a single-entity enemy (Siegebreaker: the game refuses it as a
            # unit target unless the unit climbs, mans equipment or stands on a platform)
            kind, ground = 4, 1
        out[k] = (kind, r, path, off, buf, allies, ground)
    return out


def fmt(v):
    return ("%.3f" % v).rstrip("0").rstrip(".")


def lua_block(rows):
    t = ";".join("%s=%d,%s,%s,%s,%d,%d,%d" % (k, a, fmt(r), fmt(p), fmt(o), b, h, g)
                 for k, (a, r, p, o, b, h, g) in sorted(rows.items()))
    return ("-- GENERATED by tools/gen_ww_tables.py from unit_spec_abil and battle_vortexs (the simulated 95%% drift, 80%% for\n"
            "-- Sandstorm, Lamprey's Bite, The Burning Head x2 and Arnzipal's Black Horror by the user's 2026-11-18 ruling; the\n"
            "-- build refuses a pack whose table differs from the game data). Do not hand-edit.\n"
            "-- key=kind,radius,path,offset,buffer,hits_allies,ground_only; kind 1 wave, 2 wanderer from the target centre,\n"
            "-- 3 wanderer from the target's near edge, 4 strike, 5 cone from the caster's front, 6 wanderer from the\n"
            "-- caster's front, 7 melee sweep (radius = its reach from the caster)\n"
            "FOURTH.WW_TEXT = \"%s\"\n"
            "FOURTH.WW = {}\n"
            "function FOURTH.load_ww_table()   -- a function, so the loop adds no main-chunk locals\n"
            "\tfor k, a, r, p, o, b, h, g in string.gmatch(FOURTH.WW_TEXT,\n"
            "\t\t\"([^;=]+)=(%%d),([%%d%%.]+),([%%d%%.]+),([%%d%%.]+),(%%d+),(%%d),(%%d)\") do\n"
            "\t\tFOURTH.WW[k] = { kind = tonumber(a), r = tonumber(r), path = tonumber(p), off = tonumber(o), buf = tonumber(b),\n"
            "\t\t\tallies = (h == \"1\"), ground = (g == \"1\") }\n"
            "\tend\n"
            "end\n"
            "FOURTH.load_ww_table()\n" % t)


