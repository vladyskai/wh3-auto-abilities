#!/usr/bin/env python3
"""Derive the FIRE-WHILE-MOVING land_units key set from the game's own tables (round 140).

fire_move: land_units.attribute_group carries the unit attribute "mounted_fire_move"
(unit_attributes_to_groups_junctions_tables, extracted live as gamedata/wh3/unit_attr_groups.tsv).
User ruling 2026-11-13: "Unless the unit can fire while moving, shooting and moving are incompatible."
derive() is imported by the round-140 patch (to embed the Lua table) and by the builder (to refuse a pack
whose table differs from the game data)."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_unit_size_keys import rows  # noqa: E402


def derive():
    groups = {r["attribute_group"] for r in rows("unit_attr_groups.tsv") if r.get("attribute") == "mounted_fire_move"}
    return {r["key"] for r in rows("land_units.tsv") if r.get("attribute_group", "") in groups}


def lua_block(keys):
    out = ["-- GENERATED by tools/gen_fire_move_keys.py from unit_attributes_to_groups_junctions and land_units",
           "-- (unit attribute mounted_fire_move; round 140); the build refuses a pack whose table differs.",
           "FOURTH.class_keys.fire_move = {"]
    out += ['\t["%s"] = true,' % k for k in sorted(keys)]
    out += ["}"]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    print("fire_move", len(derive()))
