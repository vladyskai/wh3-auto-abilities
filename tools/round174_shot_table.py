#!/usr/bin/env python3
"""Round 174: the SHOT table (min range, prefer-large, engaged-in-melee rule) covers the new shot-picker families
(enemy_large_value_shot, enemy_spellcaster, enemy_ground_spellcasters, enemy_commander_wavering). gen_shot_tables'
FAMILIES gains them; the table is regenerated in both copies."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
GEN = r"C:\Users\vlady\Desktop\WH3_mod\tools\gen_shot_tables.py"
SRC = r"C:\Users\vlady\Desktop\WH3_mod\mod_source\script\battle\mod\zz_test_deadly_onslaught.lua"
ANN = r"C:\Users\vlady\Desktop\WH3_mod\docs\WH3_auto_ability_annotated.lua"

g = open(GEN, encoding="utf-8").read()
OLD = '            "enemy_area_drain", "enemy_commander_value")   # ROUND 158\n'
NEW = ('            "enemy_area_drain", "enemy_commander_value",   # ROUND 158\n'
       '            "enemy_large_value_shot", "enemy_spellcaster", "enemy_ground_spellcasters",\n'
       '            "enemy_commander_wavering")   # ROUND 174\n')
if NEW not in g:
    assert g.count(OLD) == 1
    open(GEN, "w", encoding="utf-8", newline="\n").write(g.replace(OLD, NEW))
import gen_shot_tables as GS  # noqa: E402

for path in (SRC, ANN):
    s = open(path, encoding="utf-8", newline="").read()
    i = s.index("-- GENERATED by tools/gen_shot_tables.py from unit_spec_abil, projectiles")
    j = s.index("FOURTH.load_shot_table()\n", i) + len("FOURTH.load_shot_table()\n")
    keys = GS.keys_in(s)
    block = GS.lua_block(GS.derive(keys))
    s = s[:i] + block + s[j:]
    open(path, "w", encoding="utf-8", newline="").write(s)
    print(path[-30:], "SHOT keys", len(keys))
