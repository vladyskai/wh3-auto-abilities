#!/usr/bin/env python3
"""Round 146: the two GENERATED tables the blob trigger reads (user ruling 2026-11-03: baked stats only when no live
read exists, and only GENERATED from the game's own data).

  FOURTH.BLAST_TEXT   "key=radius;..." - the blast radius of every blob entry: unit_abilities.activated_projectile ->
                      projectiles.explosion_type -> projectiles_explosions.detonation_radius (metres).
  FOURTH.SPACING_TEXT "type=h,v;..."   - the close-formation spacing (metres across, metres front to back) of every
                      infantry land unit (class inf_mel / inf_mis / inf_spr) that is NOT in the generated large set and
                      whose spacing differs from the default wh_main_infantry 1.48 x 1.6 (a type not listed uses the
                      default). land_units.spacing -> unit_spacings close_formation_spacing_horizontal / _vertical.
  FOURTH.PACKED_M2    1.48 x 1.6 = 2.368 m2 per soldier (wh_main_infantry close spacing): "a tightly packed block".

Both texts are one string each, parsed at load with string.gmatch, so no key appears in quotes a second time (the harness
pins count quoted keys).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gamedata_paths as GP  # noqa: E402
import gen_unit_size_keys as SZ  # noqa: E402

DEFAULT = "wh_main_infantry"


def tsv(name):
    with open(os.path.join(GP.GAMEDATA, name), encoding="utf-8-sig") as f:
        h = f.readline().rstrip("\n").split("\t")
        f.readline()
        for line in f:
            yield dict(zip(h, line.rstrip("\n").split("\t")))


def spacing_rows():
    return {r["key"]: (float(r["close_formation_spacing_horizontal"]), float(r["close_formation_spacing_vertical"]))
            for r in tsv("unit_spacings.tsv")}


def packed_m2():
    h, v = spacing_rows()[DEFAULT]
    return round(h * v, 4)


def spacing_table():
    sp = spacing_rows()
    dh, dv = sp[DEFAULT]
    large, _ = SZ.derive()
    large = set(large)
    out = {}
    for r in tsv("land_units.tsv"):
        if r.get("class") not in ("inf_mel", "inf_mis", "inf_spr") or r["key"] in large:
            continue
        hv = sp.get(r.get("spacing", ""))
        if hv is None or (abs(hv[0] - dh) < 1e-9 and abs(hv[1] - dv) < 1e-9):
            continue
        out[r["key"]] = hv
    return out


def blast_table(keys):
    sa = {r["key"]: r for r in tsv("unit_spec_abil.tsv")}
    P = {r["key"]: r for r in tsv("projectiles.tsv")}
    E = {r["key"]: r for r in tsv("projectiles_explosions.tsv")}
    out = {}
    for k in keys:
        pr = P[sa[k]["activated_projectile"]]
        out[k] = float(E[pr["explosion_type"]]["detonation_radius"])
    return out


AP_HEAVY = 0.5     # an attack whose armour-piercing share of all its damage is at least this is "AP-heavy"


def damage_table(keys):
    """ROUND 150: per blob key - the blast's damage to every soldier it covers (projectiles_explosions
    detonation_damage / detonation_damage_ap) and the AP-heavy flag from the WHOLE profile (projectile + blast)."""
    sa = {r["key"]: r for r in tsv("unit_spec_abil.tsv")}
    P = {r["key"]: r for r in tsv("projectiles.tsv")}
    E = {r["key"]: r for r in tsv("projectiles_explosions.tsv")}
    out = {}
    for k in keys:
        p = P[sa[k]["activated_projectile"]]
        e = E[p["explosion_type"]]
        xb, xap = float(e["detonation_damage"] or 0), float(e["detonation_damage_ap"] or 0)
        tot = float(p["damage"] or 0) + float(p["ap_damage"] or 0) + xb + xap
        ap = float(p["ap_damage"] or 0) + xap
        assert xb + xap > 0, k
        out[k] = (xb, xap, 1 if tot > 0 and ap / tot >= AP_HEAVY else 0)
    return out


def defence_table():
    """ROUND 150: per infantry land unit (inf_mel / inf_mis / inf_spr, not in the generated large set): its armour value
    (unit_armour_types.armour_value via land_units.armour) and the hit points of one soldier (battle_entities.hit_points
    of its man_entity + land_units.bonus_hit_points)."""
    arm = {r["key"]: float(r["armour_value"]) for r in tsv("unit_armour_types.tsv")}
    ent = {r["key"]: float(r["hit_points"] or 0) for r in tsv("battle_entities.tsv")}
    large, _ = SZ.derive()
    large = set(large)
    out = {}
    for r in tsv("land_units.tsv"):
        if r.get("class") not in ("inf_mel", "inf_mis", "inf_spr") or r["key"] in large:
            continue
        a = arm.get(r.get("armour", ""))
        hp = ent.get(r.get("man_entity", ""), 0) + float(r.get("bonus_hit_points") or 0)
        if a is None or hp <= 0:
            continue
        out[r["key"]] = (a, hp)
    return out


def lua_block_value(dmg, defs):
    d = ";".join("%s=%s,%s,%d" % (k, fmt(b), fmt(a), h) for k, (b, a, h) in sorted(dmg.items()))
    u = ";".join("%s=%s,%s" % (k, fmt(a), fmt(hp)) for k, (a, hp) in sorted(defs.items()))
    return ("-- GENERATED by tools/gen_blob_tables.py (round 150) from projectiles, projectiles_explosions, unit_spec_abil,\n"
            "-- land_units, unit_armour_types and battle_entities (the build refuses a pack whose tables differ). Do not hand-edit.\n"
            "FOURTH.BLOB_DMG_TEXT = \"%s\"\n"
            "FOURTH.UNIT_DEF_TEXT = \"%s\"\n"
            "FOURTH.BLOB_DMG = {}\n"
            "FOURTH.UNIT_DEF = {}\n"
            "function FOURTH.load_value_tables()\n"
            "\tfor k, b, a, h in string.gmatch(FOURTH.BLOB_DMG_TEXT, \"([^;=]+)=([%%d%%.]+),([%%d%%.]+),(%%d)\") do\n"
            "\t\tFOURTH.BLOB_DMG[k] = { tonumber(b), tonumber(a), tonumber(h) }\n"
            "\tend\n"
            "\tfor k, a, hp in string.gmatch(FOURTH.UNIT_DEF_TEXT, \"([^;=]+)=([%%d%%.]+),([%%d%%.]+)\") do\n"
            "\t\tFOURTH.UNIT_DEF[k] = { tonumber(a), tonumber(hp) }\n"
            "\tend\n"
            "end\n"
            "FOURTH.load_value_tables()\n" % (d, u))


def shot_table(keys):
    """ROUND 151: per blob key - shots per cast (projectile_number x shots_per_volley x burst_size), the projectile's
    base / AP damage and bonus vs large, prefer_central_targets, breath (projectile key or ability name says breath),
    and the game's usage rules: grounded (the caster must be flying) and engaged_in_melee (not in melee)."""
    sa = {r["key"]: r for r in tsv("unit_spec_abil.tsv")}
    P = {r["key"]: r for r in tsv("projectiles.tsv")}
    names = {r["key"][29:]: r["text"] for r in tsv("unit_abilities.loc.tsv")
             if r["key"].startswith("unit_abilities_onscreen_name_")}
    use = {}
    for r in tsv("special_ability_to_invalid_usage_flags_tables.tsv"):
        use.setdefault(r["special_ability"], set()).add(r["invalid_usage_flag"])
    out = {}
    for k in keys:
        p = P[sa[k]["activated_projectile"]]
        n = 1
        for c in ("projectile_number", "shots_per_volley", "burst_size"):
            n *= max(1, int(float(p.get(c) or 1)))
        breath = 1 if ("breath" in p["key"].lower() or "breath" in names.get(k, "").lower()) else 0
        u = use.get(k, set())
        out[k] = (n, float(p["damage"] or 0), float(p["ap_damage"] or 0), float(p["bonus_v_large"] or 0),
                  1 if p.get("prefer_central_targets") == "true" else 0, breath,
                  1 if "grounded" in u else 0, 1 if "engaged_in_melee" in u else 0)
    return out


def large_def_table():
    """ROUND 151: per LARGE land unit (the generated large set): armour value and the hit points of one model - its
    man_entity + its mount's entity (when mounted) + land_units.bonus_hit_points."""
    arm = {r["key"]: float(r["armour_value"]) for r in tsv("unit_armour_types.tsv")}
    ent = {r["key"]: float(r["hit_points"] or 0) for r in tsv("battle_entities.tsv")}
    mount_ent = {r["key"]: r["entity"] for r in tsv("mounts.tsv")}
    large, _ = SZ.derive()
    large = set(large)
    out = {}
    for r in tsv("land_units.tsv"):
        if r["key"] not in large:
            continue
        a = arm.get(r.get("armour", ""))
        hp = ent.get(r.get("man_entity", ""), 0) + float(r.get("bonus_hit_points") or 0)
        if r.get("mount"):
            hp += ent.get(mount_ent.get(r["mount"], ""), 0)
        if a is None or hp <= 0:
            continue
        out[r["key"]] = (a, hp)
    return out


def lua_block_large(shots, ldefs):
    s = ";".join("%s=%d,%s,%s,%s,%d,%d,%d,%d" % ((k,) + (v[0],) + tuple(fmt(x) for x in v[1:4]) + v[4:])
                 for k, v in sorted(shots.items()))
    l = ";".join("%s=%s,%s" % (k, fmt(a), fmt(hp)) for k, (a, hp) in sorted(ldefs.items()))
    return ("-- GENERATED by tools/gen_blob_tables.py (round 151) from unit_spec_abil, projectiles, unit_abilities,\n"
            "-- special_ability_to_invalid_usage_flags, land_units, mounts, unit_armour_types and battle_entities (the build\n"
            "-- refuses a pack whose tables differ). Do not hand-edit.\n"
            "FOURTH.BLOB_SHOT_TEXT = \"%s\"\n"
            "FOURTH.LARGE_DEF_TEXT = \"%s\"\n"
            "FOURTH.BLOB_SHOT = {}\n"
            "FOURTH.LARGE_DEF = {}\n"
            "function FOURTH.load_large_tables()\n"
            "\tfor k, n, b, a, l, c, br, g, me in string.gmatch(FOURTH.BLOB_SHOT_TEXT,\n"
            "\t\t\"([^;=]+)=(%%d+),([%%d%%.]+),([%%d%%.]+),([%%d%%.]+),(%%d),(%%d),(%%d),(%%d)\") do\n"
            "\t\tFOURTH.BLOB_SHOT[k] = { tonumber(n), tonumber(b), tonumber(a), tonumber(l), tonumber(c), tonumber(br),\n"
            "\t\t\ttonumber(g), tonumber(me) }\n"
            "\tend\n"
            "\tfor k, a, hp in string.gmatch(FOURTH.LARGE_DEF_TEXT, \"([^;=]+)=([%%d%%.]+),([%%d%%.]+)\") do\n"
            "\t\tFOURTH.LARGE_DEF[k] = { tonumber(a), tonumber(hp) }\n"
            "\tend\n"
            "end\n"
            "FOURTH.load_large_tables()\n" % (s, l))


def keys_in(script_txt):
    """the keys of the script's enemy_blob entries, read from the script itself (for the build gate)"""
    import re
    out = []
    for m in re.finditer(r'trigger = "enemy_blob",\n\t\tbadge = "[^"]+",\n\t\tkeys = \{ "([^"]+)" \}', script_txt):
        out.append(m.group(1))
    return out


def fmt(v):
    return ("%.3f" % v).rstrip("0").rstrip(".")


def lua_block(blast, spacing):
    b = ";".join("%s=%s" % (k, fmt(v)) for k, v in sorted(blast.items()))
    s = ";".join("%s=%s,%s" % (k, fmt(h), fmt(v)) for k, (h, v) in sorted(spacing.items()))
    return ("-- GENERATED by tools/gen_blob_tables.py from projectiles, projectiles_explosions, land_units and\n"
            "-- unit_spacings (the build refuses a pack whose tables differ from the game data). Do not hand-edit.\n"
            "FOURTH.PACKED_M2 = %s\n"
            "FOURTH.BLAST_TEXT = \"%s\"\n"
            "FOURTH.SPACING_TEXT = \"%s\"\n"
            "FOURTH.BLAST_R = {}\n"
            "FOURTH.SPACING = {}\n"
            "function FOURTH.load_blob_tables()\n"
            "\tfor k, r in string.gmatch(FOURTH.BLAST_TEXT, \"([^;=]+)=([%%d%%.]+)\") do FOURTH.BLAST_R[k] = tonumber(r) end\n"
            "\tfor k, h, v in string.gmatch(FOURTH.SPACING_TEXT, \"([^;=]+)=([%%d%%.]+),([%%d%%.]+)\") do\n"
            "\t\tFOURTH.SPACING[k] = { tonumber(h), tonumber(v) }\n"
            "\tend\n"
            "end\n"
            "FOURTH.load_blob_tables()\n" % (fmt(packed_m2()), b, s))


if __name__ == "__main__":
    sp = spacing_table()
    print("packed m2:", packed_m2(), "| spacing rows:", len(sp), "| text bytes:", len(lua_block({}, sp)))
