#!/usr/bin/env python3
"""Round 146: the two GENERATED tables the blob trigger reads (user ruling 2026-11-03: baked stats only when no live
read exists, and only GENERATED from the game's own data).

  FOURTH.BLAST_TEXT   "key=radius;..." - the blast radius of every blob entry: unit_abilities.activated_projectile ->
                      projectiles.explosion_type -> projectiles_explosions.detonation_radius (metres).
  FOURTH.SPACING_TEXT "type=h,v;..."   - the close-formation spacing (metres across, metres front to back) of every
                      infantry land unit (class inf_mel / inf_mis / inf_spr) that is NOT in the generated large set and
                      whose spacing differs from the default wh_main_infantry 1.48 x 1.6 (a type not listed uses the
                      default). land_units.spacing -> unit_spacings close_formation_spacing_horizontal / _vertical.
  FOURTH.PACKED_M2    1.48 x 1.6 = 2.368 m2 per soldier (wh_main_infantry close spacing): "a tightly packed block".

Both texts are one string each, parsed at load with string.gmatch, so no key appears in quotes a second time (the harness
pins count quoted keys).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gamedata_paths as GP  # noqa: E402
import gen_unit_size_keys as SZ  # noqa: E402

DEFAULT = "wh_main_infantry"


def tsv(name):
    with open(os.path.join(GP.GAMEDATA, name), encoding="utf-8-sig") as f:
        h = f.readline().rstrip("\n").split("\t")
        f.readline()
        for line in f:
            yield dict(zip(h, line.rstrip("\n").split("\t")))


def spacing_rows():
    return {r["key"]: (float(r["close_formation_spacing_horizontal"]), float(r["close_formation_spacing_vertical"]))
            for r in tsv("unit_spacings.tsv")}


def packed_m2():
    h, v = spacing_rows()[DEFAULT]
    return round(h * v, 4)


def spacing_table():
    sp = spacing_rows()
    dh, dv = sp[DEFAULT]
    large, _ = SZ.derive()
    large = set(large)
    out = {}
    for r in tsv("land_units.tsv"):
        if r.get("class") not in ("inf_mel", "inf_mis", "inf_spr") or r["key"] in large:
            continue
        hv = sp.get(r.get("spacing", ""))
        if hv is None or (abs(hv[0] - dh) < 1e-9 and abs(hv[1] - dv) < 1e-9):
            continue
        out[r["key"]] = hv
    return out


def blast_table(keys):
    sa = {r["key"]: r for r in tsv("unit_spec_abil.tsv")}
    P = {r["key"]: r for r in tsv("projectiles.tsv")}
    E = {r["key"]: r for r in tsv("projectiles_explosions.tsv")}
    out = {}
    for k in keys:
        pr = P[sa[k]["activated_projectile"]]
        out[k] = float(E[pr["explosion_type"]]["detonation_radius"])
    return out


def keys_in(script_txt):
    """the keys of the script's enemy_blob entries, read from the script itself (for the build gate)"""
    import re
    out = []
    for m in re.finditer(r'trigger = "enemy_blob",\n\t\tbadge = "[^"]+",\n\t\tkeys = \{ "([^"]+)" \}', script_txt):
        out.append(m.group(1))
    return out


def fmt(v):
    return ("%.3f" % v).rstrip("0").rstrip(".")


def lua_block(blast, spacing):
    b = ";".join("%s=%s" % (k, fmt(v)) for k, v in sorted(blast.items()))
    s = ";".join("%s=%s,%s" % (k, fmt(h), fmt(v)) for k, (h, v) in sorted(spacing.items()))
    return ("-- GENERATED by tools/gen_blob_tables.py from projectiles, projectiles_explosions, land_units and\n"
            "-- unit_spacings (the build refuses a pack whose tables differ from the game data). Do not hand-edit.\n"
            "FOURTH.PACKED_M2 = %s\n"
            "FOURTH.BLAST_TEXT = \"%s\"\n"
            "FOURTH.SPACING_TEXT = \"%s\"\n"
            "FOURTH.BLAST_R = {}\n"
            "FOURTH.SPACING = {}\n"
            "function FOURTH.load_blob_tables()\n"
            "\tfor k, r in string.gmatch(FOURTH.BLAST_TEXT, \"([^;=]+)=([%%d%%.]+)\") do FOURTH.BLAST_R[k] = tonumber(r) end\n"
            "\tfor k, h, v in string.gmatch(FOURTH.SPACING_TEXT, \"([^;=]+)=([%%d%%.]+),([%%d%%.]+)\") do\n"
            "\t\tFOURTH.SPACING[k] = { tonumber(h), tonumber(v) }\n"
            "\tend\n"
            "end\n"
            "FOURTH.load_blob_tables()\n" % (fmt(packed_m2()), b, s))


if __name__ == "__main__":
    sp = spacing_table()
    print("packed m2:", packed_m2(), "| spacing rows:", len(sp), "| text bytes:", len(lua_block({}, sp)))
