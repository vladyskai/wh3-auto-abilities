#!/usr/bin/env python3
"""Round 156: the SHOT table for the magic-missile families (user rulings 2026-11-15), GENERATED from the game data
(CLAUDE.md rule 4: never hand-typed). One row per key:

  key=<no_melee>,<prefer_large>,<min_range>
    no_melee     1 when special_ability_to_invalid_usage_flags lists engaged_in_melee (the game refuses the cast
                 while the caster is in melee)
    prefer_large 1 when the activated projectile's bonus_v_large is above its bonus_v_infantry (Focused Shot)
    min_range    unit_spec_abil.min_range in metres (an enemy closer than it cannot be targeted)

keys_in(script_txt) reads the keys of the script's entries on the round-156 families (for the build gate);
lua_block(rows) is the text embedded in the mod.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gamedata_paths as GP  # noqa: E402

FAMILIES = ("enemy_large_shot", "enemy_single_shot", "enemy_infantry_shot", "enemy_melee_or_fast",
            "enemy_melee_or_shooting")


def tsv(name):
    with open(os.path.join(GP.GAMEDATA, name), encoding="utf-8-sig") as f:
        h = f.readline().rstrip("\n").split("\t")
        f.readline()
        for line in f:
            yield dict(zip(h, line.rstrip("\n").split("\t")))


def fmt(v):
    return ("%.3f" % v).rstrip("0").rstrip(".")


def derive(keys):
    usa = {r["key"]: r for r in tsv("unit_spec_abil.tsv")}
    prj = {r["key"]: r for r in tsv("projectiles.tsv")}
    nomelee = {r["special_ability"] for r in tsv("special_ability_to_invalid_usage_flags_tables.tsv")
               if r["invalid_usage_flag"] == "engaged_in_melee"}
    out = {}
    for k in keys:
        a = usa[k]
        p = prj.get(a["activated_projectile"])
        pl = 0
        if p is not None and float(p["bonus_v_large"] or 0) > float(p["bonus_v_infantry"] or 0):
            pl = 1
        out[k] = (1 if k in nomelee else 0, pl, float(a["min_range"] or 0))
    return out


def keys_in(script_txt):
    out = []
    for m in re.finditer(r'trigger = "(%s)",\n\t\tbadge = "[^"]+",\n\t\tkeys = \{ "([^"]+)" \}' % "|".join(FAMILIES),
                         script_txt):
        out.append(m.group(2))
    return sorted(out)


def lua_block(rows):
    t = ";".join("%s=%d,%d,%s" % (k, a, b, fmt(c)) for k, (a, b, c) in sorted(rows.items()))
    return ("-- GENERATED by tools/gen_shot_tables.py from unit_spec_abil, projectiles and the invalid-usage flags (the\n"
            "-- build refuses a pack whose table differs from the game data). Do not hand-edit.\n"
            "FOURTH.SHOT_TEXT = \"%s\"\n"
            "FOURTH.SHOT = {}\n"
            "function FOURTH.load_shot_table()   -- a function, so the loop adds no main-chunk locals\n"
            "\tfor k, a, b, c in string.gmatch(FOURTH.SHOT_TEXT, \"([^;=]+)=(%%d),(%%d),([%%d%%.]+)\") do\n"
            "\t\tFOURTH.SHOT[k] = { tonumber(a), tonumber(b), tonumber(c) }\n"
            "\tend\n"
            "end\n"
            "FOURTH.load_shot_table()\n" % t)


