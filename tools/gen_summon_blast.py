#!/usr/bin/env python3
"""Round 181: the blast radius of a summon that explodes (Surprise Squig!: user, 2026-11-20, review row 28, "implement
blob with clearance"). The ability's spawned_unit (unit_spec_abil) -> that unit's abilities (land_units_to_unit_
abilites_junctions, gamedata/wh3/land_abil.tsv) -> each one's bombardment -> its reach (radius_spread + the projectile's
detonation radius, tools/gen_ww_tables.bombardment); the widest wins. Surprise Squig: Explosive Squigs, 'Squigs Go Boom'
(radius 1 + 20 m) = 21 m; the game marks it as hitting allies.
keys_in(script) reads the keys on enemy_summon_blob; derive() / lua_block() feed the round-181 patch and the builder."""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_ww_tables as GW  # noqa: E402

FAMILY = "enemy_summon_blob"


def keys_in(script_txt):
    return sorted(set(re.findall(r'trigger = "%s",\n\t\tbadge = "[^"]+",\n\t\tkeys = \{ "([^"]+)" \}' % FAMILY, script_txt)))


def derive(keys):
    usa = {r["key"]: r for r in GW.tsv("unit_spec_abil.tsv")}
    abil = {}
    for r in GW.tsv("land_abil.tsv"):
        abil.setdefault(r["land_unit"], []).append(r["ability"])
    out = {}
    for k in keys:
        unit = usa[k]["spawned_unit"]
        assert unit, "%s spawns nothing" % k
        best = None
        for a in abil.get(unit, []):
            b = GW.bombardment(usa[a]) if a in usa else None
            if b is not None and (best is None or b[0] > best):
                best = b[0]
        assert best is not None, "%s: the spawned %s has no exploding ability" % (k, unit)
        out[k] = best
    return out


def fmt(v):
    return ("%.3f" % v).rstrip("0").rstrip(".")


def lua_block(rows):
    t = ";".join("%s=%s" % (k, fmt(v)) for k, v in sorted(rows.items()))
    return ("-- GENERATED by tools/gen_summon_blast.py from unit_spec_abil (spawned_unit), land_units_to_unit_abilites_junctions\n"
            "-- and projectile_bombardments / projectiles / projectiles_explosions: the blast of a summon that explodes. The build\n"
            "-- refuses a pack whose table differs from the game data. Do not hand-edit.\n"
            "FOURTH.SUMMON_BLAST_TEXT = \"%s\"\n"
            "FOURTH.SUMMON_BLAST_R = {}\n"
            "function FOURTH.load_summon_blast()   -- a function, so the loop adds no main-chunk locals\n"
            "\tfor k, r in string.gmatch(FOURTH.SUMMON_BLAST_TEXT, \"([^;=]+)=([%%d%%.]+)\") do FOURTH.SUMMON_BLAST_R[k] = tonumber(r) end\n"
            "end\n"
            "FOURTH.load_summon_blast()\n" % t)


if __name__ == "__main__":
    print(derive(["wh3_dlc25_character_abilities_surprise_squig"]))
