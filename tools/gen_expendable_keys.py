#!/usr/bin/env python3
"""Round 163: the EXPENDABLE land_units key set from the game's own tables (user ruling 2026-11-16: "Some units in the
game are expendable, so it would be cool if the friendly fire checks skipped these units" -> "Game's set + cheap
undead"; the cheap part is the live value test in the mod, not a table).

expendable: land_units.attribute_group carries the unit attribute "expendable"
(unit_attributes_to_groups_junctions_tables, extracted as gamedata/wh3/unit_attr_groups.tsv).
One string, read at load with string.gmatch, so no unit key appears in quotes a second time.
derive() is imported by the round-163 patch (to embed the text) and by the builder (to refuse a pack whose table
differs from the game data)."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_unit_size_keys import rows  # noqa: E402


def derive():
    groups = {r["attribute_group"] for r in rows("unit_attr_groups.tsv") if r.get("attribute") == "expendable"}
    return {r["key"] for r in rows("land_units.tsv") if r.get("attribute_group", "") in groups}


def lua_block(keys):
    return ("-- GENERATED by tools/gen_expendable_keys.py from unit_attributes_to_groups_junctions and land_units (round\n"
            "-- 163, the game's 'expendable' attribute); the build refuses a pack whose table differs. Do not hand-edit.\n"
            "FOURTH.EXPENDABLE_TEXT = \"%s\"\n"
            "FOURTH.class_keys.expendable = {}\n"
            "function FOURTH.load_expendable()   -- a function, so the loop adds no main-chunk locals\n"
            "\tfor k in string.gmatch(FOURTH.EXPENDABLE_TEXT, \"[^;]+\") do FOURTH.class_keys.expendable[k] = true end\n"
            "end\n"
            "FOURTH.load_expendable()\n" % ";".join(sorted(keys)))


if __name__ == "__main__":
    e = derive()
    print("expendable", len(e))
