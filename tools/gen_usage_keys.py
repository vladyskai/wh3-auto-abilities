"""Round 165 (night audit 2026-11-17): the game's CASTER usage rules (special_ability_to_invalid_usage_flags) for the
mod's own keys, as one generated text the mod reads at load. Each rule names a state in which the game refuses the
cast; the mod skips the attempt while its live read says the caster is in that state.

Codes (only the flags with a live battle read; the rest are listed by report() and stay unmodelled):
  M  engaged_in_melee            refused while the caster is in melee          (is_in_melee() == true)
  G  grounded                    refused while the caster is on the ground     (is_currently_flying() ~= true)
  F  flying_currently            refused while the caster flies                (is_currently_flying() == true)
  V  moving                      refused while the caster moves                (is_moving() == true)
  W  morale_is_wavering_or_lower refused while the caster wavers               (is_wavering() == true)
  hN health_below_N%             refused below N% health                       (health < N)
  HN health_above_N%             refused above N% health                       (health > N)
  L  unit_is_not_large           refused unless the caster is a large unit     (the GENERATED large set)

Format: key=CODES;key=CODES (codes joined with '.'). One string, read at load with string.gmatch, so no ability key
appears in quotes a second time (the harness pins count quoted keys).
derive(src) is imported by the round-165 patch (to embed the text) and by the builder (to refuse a pack whose table
differs from the game data)."""
