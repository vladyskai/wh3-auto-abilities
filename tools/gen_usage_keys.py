SRC = r"C:\Users\vlady\Desktop\WH3_mod\mod_source\script\battle\mod\zz_test_deadly_onslaught.lua"
SIMPLE = {"engaged_in_melee": "M", "grounded": "G", "flying_currently": "F", "moving": "V",
          "morale_is_wavering_or_lower": "W", "unit_is_not_large": "L"}
# not modelled: siege and phase states (the poll never runs in them or never sees them), routing (every evaluator
# already skips a routing caster), and the flags with no battle read
UNMODELLED = {"climbing", "manning_equipment", "on_a_platform", "on_a_platform_only", "climbing_manning_eq_on_platform",
              "flying_over_platform", "flying_over_invalid_location", "docked", "phase_is_deployment",
              "phase_is_the_end_phase", "morale_is_broken_or_lower", "hp_replenish_cap_reached",
              "enemies_in_intercept_range", "cannot_perform_missile_attack", "ground_unit", "flying_unit"}


def mod_keys(src_txt):
    """every ability key in the ABILITIES table, with its entry's family"""
    out = {}
    tab = src_txt.split("\nlocal ABILITIES = {", 1)[1].split("\n}\n", 1)[0]
    for m in re.finditer(r'\{ marker = "[^"]+", name = "(?:[^"\\]|\\.)*", trigger = "([^"]+)",(.*?)\n\t\tox = ', tab, re.S):
        body = re.sub(r"--[^\n]*", "", m.group(2))   # comments may sit between the fields
        for k in re.findall(r'"([^"]+)"', body.split("keys = {", 1)[1].split("}", 1)[0]):
            out[k] = m.group(1)
    return out


def code(flag):
    if flag in SIMPLE:
        return SIMPLE[flag]
    m = re.fullmatch(r"health_(below|above)_(\d+)%", flag)
    if m:
        return ("h" if m.group(1) == "below" else "H") + m.group(2)
    return None


def derive(src_txt=None):
    if src_txt is None:
        src_txt = open(SRC, encoding="utf-8").read()
    keys = mod_keys(src_txt)
    use = collections.defaultdict(set)
    for r in rows("special_ability_to_invalid_usage_flags_tables.tsv"):
        k, f = r["special_ability"], r["invalid_usage_flag"]
        if k in keys:
            c = code(f)
            if c is not None:
                use[k].add(c)
            elif f not in UNMODELLED:
                raise SystemExit("gen_usage_keys: unknown usage flag %r on %s" % (f, k))
    return {k: ".".join(sorted(v)) for k, v in use.items()}


def text(table):
    return ";".join("%s=%s" % (k, table[k]) for k in sorted(table))


def lua_block(table):
    return ("-- GENERATED by tools/gen_usage_keys.py from special_ability_to_invalid_usage_flags (round 165, the game's\n"
            "-- caster usage rules); the build refuses a pack whose table differs. Do not hand-edit.\n"
            "FOURTH.USAGE_TEXT = \"%s\"\n" % text(table))


# THE ALLY TARGET RULES (special_ability_to_invalid_target_flags): what the shared ally picker (ab_pick_ally) may
# offer as the cast target. Only flags with a live read or a generated set; the family classes (beast, missile, war
# machine, Hell-Forged, construct, monster, Overseer, broken) stay where they are.
TARGET = {"unit_is_not_commander_class": "C",   # the target must be a Lord or Hero
          "unit_is_commander_class": "c",       # never a Lord or Hero
          "unit_is_not_large": "L",             # the target must be large (the GENERATED large set)
          "unit_is_large": "l",                 # never a large unit
          "flying_currently": "F",              # never a unit that is flying now
          "living_unit": "U",                   # the target must be undead (the GENERATED undead set)
          "undead_unit": "u",                   # never an undead unit
          "unit_is_not_single_entity": "S",     # the target must be a single entity (the GENERATED single set)
          "is_not_missile_unit": "P",           # the target must be a missile unit (the missile set)
          "unit_is_not_a_lizard_unit": "Z",     # ROUND 180: a Lizardmen unit (the GENERATED lizard set, user 'set A')
          "unit_is_not_tiger_warrior": "T",     # ROUND 180: a Tiger Warrior unit (the GENERATED tiger set)
          # ROUND 192: despite its name, the flag's own text reads 'Unit is not a Clan Moulder Monster': the target must
          # BE one (the GENERATED moulder set; Shock Collar, Remouldered)
          "unit_is_moulder_monster": "M"}


def derive_target(src_txt=None):
    if src_txt is None:
        src_txt = open(SRC, encoding="utf-8").read()
    keys = mod_keys(src_txt)
    t = collections.defaultdict(set)
    for r in rows("special_ability_to_invalid_target_flags_tables.tsv"):
        k, f = r["special_ability"], r["invalid_target"]
        if k in keys and f in TARGET:
            t[k].add(TARGET[f])
    return {k: ".".join(sorted(v)) for k, v in t.items()}


def target_text(table):
    return ";".join("%s=%s" % (k, table[k]) for k in sorted(table))


def report(src_txt=None):
    if src_txt is None:
        src_txt = open(SRC, encoding="utf-8").read()
    keys = mod_keys(src_txt)
    t = derive(src_txt)
    print("mod keys:", len(keys), " keys with a modelled usage rule:", len(t))
    by = collections.Counter()
    for k, v in t.items():
        for c in v.split("."):
            by[c] += 1
    print("codes:", dict(sorted(by.items())))
    unm = collections.Counter()
    for r in rows("special_ability_to_invalid_usage_flags_tables.tsv"):
        if r["special_ability"] in keys and code(r["invalid_usage_flag"]) is None:
            unm[r["invalid_usage_flag"]] += 1
    print("unmodelled flags on mod keys:", dict(unm.most_common()))
    return keys, t


if __name__ == "__main__":
    keys, t = report()
    for k in sorted(t):
        print("  %-70s %-28s %s" % (k, keys[k], t[k]))
