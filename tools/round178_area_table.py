#!/usr/bin/env python3
"""Round 178: the AREA table (max_damaged_entities) for enemy_area_drain, regenerated after Chain Lightning x2 and The
Soulstealer joined the family. The block is cut at the call that starts a line (the round-174 lesson)."""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_shot_tables as G  # noqa: E402

SRC = r"C:\Users\vlady\Desktop\WH3_mod\mod_source\script\battle\mod\zz_test_deadly_onslaught.lua"
ANN = r"C:\Users\vlady\Desktop\WH3_mod\docs\WH3_auto_ability_annotated.lua"
HEAD = "-- GENERATED by tools/gen_shot_tables.py from phase_junc and phases (max_damaged_entities;"
TAIL = "\nFOURTH.load_area_table()\n"
for path in (SRC, ANN):
    s = open(path, encoding="utf-8", newline="").read()
    keys = set(re.findall(r'trigger = "enemy_(?:area_drain|most_models)",\n\t\tbadge = "[^"]+",\n\t\tkeys = \{ "([^"]+)" \}', s))
    assert s.count(HEAD) == 1
    i = s.index(HEAD)
    j = s.index(TAIL, i) + len(TAIL)
    block = G.area_block(G.area_rows(keys))
    assert block.startswith(HEAD), block[:80]
    s = s[:i] + block + s[j:]
    assert s.count("function FOURTH.load_area_table()") == 1 and s.count(TAIL) == 1
    open(path, "w", encoding="utf-8", newline="").write(s)
    print(path[-30:], "AREA keys", len(keys))
