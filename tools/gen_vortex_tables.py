#!/usr/bin/env python3
"""Round 159: the VORTEX table, GENERATED from the game data (CLAUDE.md rule 4: never hand-typed).

  FOURTH.VORTEX_TEXT "key=radius;..." - the blast radius (metres) of every entry on the round-159 blast families whose
                     blast is a VORTEX (unit_spec_abil.vortex -> battle_vortexs; the largest start_radius / goal_radius
                     along the vortex and its subsequent_vortex chain), for:
                       * melee_clear, fly_dive, last_stand_clear (the self-centred blasts the game marks affects_allies:
                         none of our other units within radius + SHOT_SAFE_M of the caster);
                       * enemy_blob_vortex (a blob attack whose blast is a vortex, not a projectile);
                       * enemy_commander_value entries whose vortex affects allies (Deathmaster's Sigil: the target keeps
                         radius + SHOT_SAFE_M clear of our units).

One string, parsed at load with string.gmatch, so no key appears in quotes a second time (the harness pins count
quoted keys).

  keys_in(script_txt) -> sorted keys of those entries (single-key entries)
  derive(keys)        -> {key: radius}  (only the keys that qualify)
  lua_block(rows)     -> the text embedded in the mod
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gamedata_paths as GP  # noqa: E402

SELF_FAMILIES = ("melee_clear", "fly_dive", "last_stand_clear",
                 "melee_clear_block")   # ROUND 181: Land Mine (melee_clear + 60 soldiers in its 25 m blast)
FAMILIES = SELF_FAMILIES + ("enemy_blob_vortex", "enemy_commander_value")


def tsv(name):
    with open(os.path.join(GP.GAMEDATA, name), encoding="utf-8-sig") as f:
        h = f.readline().rstrip("\n").split("\t")
        f.readline()
        for line in f:
            yield dict(zip(h, line.rstrip("\n").split("\t")))


def fmt(v):
    return ("%.3f" % v).rstrip("0").rstrip(".")


def keys_in(script_txt):
    out = {}
    for m in re.finditer(r'trigger = "(%s)",\n\t\tbadge = "[^"]+",\n\t\tkeys = \{ "([^"]+)" \}' % "|".join(FAMILIES),
                         script_txt):
        out[m.group(2)] = m.group(1)
    return out


def chain(vx, v):
    seen, out = set(), []
    while v and v not in seen:
        seen.add(v)
        r = vx.get(v)
        if r is None:
            break
        out.append(r)
        v = r.get("subsequent_vortex", "")
    return out


def bombardment_r(usa, k):
    """ROUND 185: a self-centred BOMBARDMENT (the Master Rune of Immolation): (radius, affects_allies) = the shell's
    explosion detonation_radius + the bombardment's radius_spread, and the explosion's affects_allies; None when the
    ability has no bombardment with an explosion."""
    bk = usa[k].get("bombardment", "")
    if not bk:
        return None
    bomb = {r["bombardment_key"]: r for r in tsv("projectile_bombardments.tsv")}.get(bk)
    if bomb is None:
        return None
    prj = {r["key"]: r for r in tsv("projectiles.tsv")}.get(bomb["projectile_type"])
    if prj is None:
        return None
    ex = {r["key"]: r for r in tsv("projectiles_explosions.tsv")}.get(prj["explosion_type"])
    if ex is None:
        return None
    return (float(ex["detonation_radius"] or 0) + float(bomb["radius_spread"] or 0), ex["affects_allies"] == "true")


def derive(key_fams):
    usa = {r["key"]: r for r in tsv("unit_spec_abil.tsv")}
    vx = {r["vortex_key"]: r for r in tsv("battle_vortexs.tsv")}
    out = {}
    for k, fam in sorted(key_fams.items()):
        rows = chain(vx, usa[k]["vortex"])
        if not rows and fam in SELF_FAMILIES and bombardment_r(usa, k) is not None:   # ROUND 185
            r, allies = bombardment_r(usa, k)
            assert allies, "%s is on %s but its bombardment does not affect allies" % (k, fam)
            out[k] = r
            continue
        if not rows:
            assert fam == "enemy_commander_value", "%s (%s) has no vortex" % (k, fam)
            continue
        allies = any(r["affects_allies"] == "true" for r in rows)
        if fam == "enemy_commander_value" and not allies:
            continue
        if fam in SELF_FAMILIES:
            assert allies, "%s is on %s but its blast does not affect allies" % (k, fam)
        out[k] = max(max(float(r["start_radius"] or 0), float(r["goal_radius"] or 0)) for r in rows)
    return out


def lua_block(rows):
    t = ";".join("%s=%s" % (k, fmt(v)) for k, v in sorted(rows.items()))
    return ("-- GENERATED by tools/gen_vortex_tables.py from unit_spec_abil and battle_vortexs (the blast radius of every\n"
            "-- round-159 blast entry; the build refuses a pack whose table differs from the game data). Do not hand-edit.\n"
            "FOURTH.VORTEX_TEXT = \"%s\"\n"
            "FOURTH.VORTEX_R = {}\n"
            "function FOURTH.load_vortex_table()   -- a function, so the loop adds no main-chunk locals\n"
            "\tfor k, r in string.gmatch(FOURTH.VORTEX_TEXT, \"([^;=]+)=([%%d%%.]+)\") do FOURTH.VORTEX_R[k] = tonumber(r) end\n"
            "end\n"
            "FOURTH.load_vortex_table()\n" % t)


