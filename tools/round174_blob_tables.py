#!/usr/bin/env python3
"""Round 174: six blob attacks left enemy_blob (Amber Bow, Gaze of Nagash -> enemy_large_shot; Hand of Gods, Shem's
Burning Gaze, Goggly Glare, Vindictive Glare -> enemy_large_value_shot). The three GENERATED blob table blocks (blast /
spacing, damage / defence, shot / large) are keyed on the enemy_blob keys, so each is regenerated by its own generator
in both copies (the round-146 / 150 / 151 build gates compare them).

FIRST VERSION BUG (repaired in the files by tools/round174_blob_repair.py): the tail matched 'FOURTH.load_X()' inside
the function header 'function FOURTH.load_X()', so the old body stayed behind. The tail now starts at a line start."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_blob_tables as G  # noqa: E402

SRC = r"C:\Users\vlady\Desktop\WH3_mod\mod_source\script\battle\mod\zz_test_deadly_onslaught.lua"
ANN = r"C:\Users\vlady\Desktop\WH3_mod\docs\WH3_auto_ability_annotated.lua"
BLOCKS = [
    ("-- GENERATED by tools/gen_blob_tables.py from projectiles, projectiles_explosions, land_units and\n",
     "\nFOURTH.load_blob_tables()\n", lambda k: G.lua_block(G.blast_table(k), G.spacing_table())),
    ("-- GENERATED by tools/gen_blob_tables.py (round 150)", "\nFOURTH.load_value_tables()\n",
     lambda k: G.lua_block_value(G.damage_table(k), G.defence_table())),
    ("-- GENERATED by tools/gen_blob_tables.py (round 151)", "\nFOURTH.load_large_tables()\n",
     lambda k: G.lua_block_large(G.shot_table(k), G.large_def_table())),
]
for path in (SRC, ANN):
    s = open(path, encoding="utf-8", newline="").read()
    keys = G.keys_in(s)
    for head, tail, make in BLOCKS:
        assert s.count(head) == 1, (path[-12:], head[:50])
        i = s.index(head)
        j = s.index(tail, i) + len(tail)
        new = make(keys)
        changed = s[i:j] != new
        s = s[:i] + new + s[j:]
        print(path[-30:], head[30:62].strip(), "changed" if changed else "unchanged")
    open(path, "w", encoding="utf-8", newline="").write(s)
    print(path[-30:], "blob keys", len(keys))
