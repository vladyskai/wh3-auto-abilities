def one(s, a, b, what):
    assert s.count(a) == 1, (what, s.count(a))
    return s.replace(a, b)


def patch(path, live, cone):
    s = open(path, encoding="utf-8", newline="").read()
    assert "FOURTH.WW_CONE_TEXT" not in s, "already patched: " + path
    s = one(s, A_TABLE, N_TABLE % cone, "table")
    s = one(s, A_COVER, N_COVER, "cover")
    s = one(s, A_PT1, N_PT1, "pt1")
    s = one(s, A_PT2, N_PT2, "pt2")
    s = one(s, A_EXACT, N_EXACT, "exact")
    s = one(s, A_VALUE, N_VALUE, "value")
    if live:
        s = one(s, A_REASON, N_REASON, "reason")
    open(path, "w", encoding="utf-8", newline="").write(s)
    print("patched", path)


def main():
    os.makedirs(BK, exist_ok=True)
    for src, name in ((LIVE, "pre205_live.lua"), (ANN, "pre205_ann.lua")):
        dst = os.path.join(BK, name)
        if not os.path.exists(dst):
            shutil.copy2(src, dst)
    cone = GC.text(GC.derive(open(LIVE, encoding="utf-8").read()))
    assert cone.count("=") == 19, cone.count("=")
    patch(LIVE, True, cone)
    patch(ANN, False, cone)


if __name__ == "__main__":
    main()
