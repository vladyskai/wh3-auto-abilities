#!/usr/bin/env python3
"""Derive each automated ability's LOCK TIME from the game's own unit_spec_abil table (round 141).

lock = active_time (when > 0) + recharge_time, in seconds: the game starts the recharge when the effect ENDS (QA battle
5, Restore: cast 208 s, effect 24 s, recharge 60 s, refused at 268 s). Single-use rows (num_uses 1), toggles
(active_time -1 with no recharge) and rows with no recharge are left out: they are never "recharging".
The mod uses it to know which of a unit's abilities, cast by the mod, are still recharging (the recharge reducers,
user rulings 2026-11-13). Campaign bonuses can make the real recharge shorter; there is no battle read for it.
derive() is imported by the round-141 patch (to embed the Lua table) and by the builder (to refuse a pack whose
table differs from the game data)."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_unit_size_keys import rows  # noqa: E402
import build_ability_database as bd  # noqa: E402


def derive():
    entries, _, _ = bd.mod_entries()
    mod_keys = {k for e in entries for k in e["keys"]}
    out = {}
    for r in rows("unit_spec_abil.tsv"):
        k = r["key"]
        if k not in mod_keys:
            continue
        try:
            active, recharge, uses = float(r["active_time"]), float(r["recharge_time"]), int(float(r["num_uses"]))
        except ValueError:
            continue
        if recharge <= 0 or uses == 1:
            continue
        out[k] = int(round(max(active, 0) + recharge))
    return out


def lua_block(table):
    # The keys are stored as one text ("key=seconds key=seconds ...") and read into FOURTH.RECHARGE_S at load, so no
    # ability key appears a second time in quotes (the harness pins count each key's quoted occurrences). The reader
    # is a function, so its loop locals never touch the main chunk's 200-local ceiling.
    items = ["%s=%d" % (k, table[k]) for k in sorted(table)]
    chunks = [" ".join(items[i:i + 6]) for i in range(0, len(items), 6)]
    lines = ["-- GENERATED by tools/gen_recharge_keys.py from unit_spec_abil (round 141): active_time + recharge_time,",
             "-- seconds; the build refuses a pack whose table differs from the game data.",
             "FOURTH.RECHARGE_TEXT = \"\""]
    lines += ["\t.. \" %s\"" % c for c in chunks]
    lines += ["FOURTH.RECHARGE_S = {}",
              "function FOURTH.load_recharge()",
              "\tfor k, v in string.gmatch(FOURTH.RECHARGE_TEXT, \"([%w_]+)=(%d+)\") do",
              "\t\tFOURTH.RECHARGE_S[k] = tonumber(v)",
              "\tend",
              "end",
              "FOURTH.load_recharge()"]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    t = derive()
    print("keys", len(t))
