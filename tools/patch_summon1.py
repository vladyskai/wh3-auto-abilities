def rd(p):
    return open(p, "rb").read().decode("utf-8")

def wr(p, s):
    assert "\r" not in s
    open(p, "wb").write(s.encode("utf-8"))

def sub(s, old, new, count=1, tag=""):
    n = s.count(old)
    assert n == count, "anchor %r hit %d times (want %d) %s" % (old[:70], n, count, tag)
    return s.replace(old, new)

