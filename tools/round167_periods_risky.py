#!/usr/bin/env python3
"""Round 167 (harness 166): no final period, and the safer defaults (user rulings 2026-11-17, after the Dark Elves battle).

  * NO FINAL PERIOD (user: "Do you need to put a point at the end of a sentence when there is no sentence after it?
    Please remove the point. Check the other tooltips also."): the mod sets exactly two tooltips, the M/A badge card
    (FOURTH.compose_card) and the ALL button (FOURTH.ALL_TIP). Neither ends with '.' now.
  * SAFER DEFAULTS (user: "Please implement Safer defaults for Rampage and self-damage abilities. They stay on M even in
    families that start armed"): GENERATED FOURTH.RISKY_TEXT (tools/gen_risky_keys.py: the game's 'rampage' phase
    attribute on the caster or its allies, and phases that damage the caster). An entry with a risky key never starts
    armed; a badge click still arms it (the explicit choice wins).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_risky_keys as GR  # noqa: E402

SRC = r"C:\Users\vlady\Desktop\WH3_mod\mod_source\script\battle\mod\zz_test_deadly_onslaught.lua"
ANN = r"C:\Users\vlady\Desktop\WH3_mod\docs\WH3_auto_ability_annotated.lua"

RET_OLD = '\treturn table.concat(parts, "; ") .. "."   -- ROUND 166: no name, no \'on A:\'\n'
RET_NEW = '\treturn table.concat(parts, "; ")   -- ROUND 166: no name, no \'on A:\'; ROUND 167: no final period\n'
ALL_OLD = 'FOURTH.ALL_TIP = "Arm or disarm every automatic ability of the selected unit(s)."\n'
ALL_NEW = ('-- ROUND 167 (user, 2026-11-17): no final period on a one-sentence tooltip\n'
           'FOURTH.ALL_TIP = "Arm or disarm every automatic ability of the selected unit(s)"\n')
DEF_END = '\tally_melee_buff = true,   -- ROUND 161 (user ruling 2026-11-16: the 14 ally melee buffs, "Whole family")\n}\n'
RISKY = '''-- ROUND 167 - THE SAFER DEFAULTS (user ruling 2026-11-17): an ability that makes OUR unit rampage (it leaves your
-- control) or damages its own caster never starts armed, even in a family above; a badge click still arms it.
-- GENERATED by tools/gen_risky_keys.py from special_ability_phase_attribute_effects ('rampage', positive, on the caster
-- or its allies) and phases (damage_amount on the caster); R = rampage, D = self-damage. The build refuses a pack whose
-- table differs from the game data. Do not hand-edit.
FOURTH.RISKY_TEXT = "%s"
FOURTH.RISKY = {}
function FOURTH.load_risky_table()   -- a function, so the loop adds no main-chunk locals
	for k, f in string.gmatch(FOURTH.RISKY_TEXT, "([^;=]+)=([RD]+)") do FOURTH.RISKY[k] = f end
end
FOURTH.load_risky_table()
-- true when any key of the entry is risky
function FOURTH.entry_risky(ability)
	for _, k in ipairs(ability.keys or {}) do
		if FOURTH.RISKY[k] ~= nil then return true end
	end
	return false
end
'''
DEFON_OLD = ("\tability.default_on = (FOURTH.DEFAULT_ON_TRIGGERS[ability.trigger] == true)\n"
             "\t\tand ZZ_AUTO_TEST_NO_DEFAULTS ~= true\n")
DEFON_NEW = ("\tability.default_on = (FOURTH.DEFAULT_ON_TRIGGERS[ability.trigger] == true)\n"
             "\t\tand ZZ_AUTO_TEST_NO_DEFAULTS ~= true\n"
             "\t\tand not FOURTH.entry_risky(ability)   -- ROUND 167: rampage and self-damage start on M\n")


def main():
    rows = GR.derive(open(SRC, encoding="utf-8").read())
    block = RISKY % GR.text(rows)
    print("risky keys", len(rows))
    for path in (SRC, ANN):
        s = open(path, encoding="utf-8", newline="").read()
        assert "ROUND 167" not in s
        for o, n in ((RET_OLD, RET_NEW), (ALL_OLD, ALL_NEW), (DEF_END, DEF_END + block), (DEFON_OLD, DEFON_NEW)):
            assert s.count(o) == 1, (path[-12:], o[:60], s.count(o))
            s = s.replace(o, n)
        assert "\u2014" not in s
        open(path, "w", encoding="utf-8", newline="").write(s)
        print(path, "patched")


if __name__ == "__main__":
    main()
