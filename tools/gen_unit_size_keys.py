#!/usr/bin/env python3
"""Derive the LARGE and SINGLE-ENTITY land_units key sets from the game's own tables (round 135).

The engine's invalid-target flags unit_is_not_large / unit_is_not_single_entity have no battle API
read, so (CLAUDE.md rule 4) the sets are GENERATED here, never hand-typed:

  large  : the unit's man_entity OR its mount's entity (land_units.mount -> mounts.entity) has
           battle_entities.size large or very_large (a Lord on a dragon is large through its mount);
  single : every main_units row for the land unit has num_men == 1.

    python gen_unit_size_keys.py          # print the counts
derive() is imported by the round-135 patch (to embed the Lua tables) and by the builder (to refuse
a pack whose embedded tables differ from the game data).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gamedata_paths import GAMEDATA  # noqa: E402


def rows(name):
    with open(os.path.join(GAMEDATA, name), encoding="utf-8") as f:
        hdr = f.readline().rstrip("\n").split("\t")
        f.readline()
        for line in f:
            c = line.rstrip("\n").split("\t")
            if len(c) >= len(hdr) - 1 and c[0]:
                yield dict(zip(hdr, c))


def derive():
    size = {r["key"]: r["size"] for r in rows("battle_entities.tsv")}
    mount_ent = {r["key"]: r["entity"] for r in rows("mounts.tsv")}
    big = {"large", "very_large"}
    large = set()
    for r in rows("land_units.tsv"):
        ents = [r.get("man_entity", "")]
        m = r.get("mount", "")
        if m:
            ents.append(mount_ent.get(m, ""))
        if any(size.get(e) in big for e in ents if e):
            large.add(r["key"])
    men = {}
    for r in rows("main_units.tsv"):
        lu = r.get("land_unit", "")
        if lu:
            men.setdefault(lu, set()).add(r.get("num_men", ""))
    single = {lu for lu, s in men.items() if s == {"1"}}
    return large, single


def lua_block(large, single):
    out = ["-- GENERATED by tools/gen_unit_size_keys.py from battle_entities, mounts, land_units and",
           "-- main_units (round 135); the build refuses a pack whose tables differ from the game data.",
           "-- large: man_entity or mount entity size large/very_large. single: num_men == 1.",
           "FOURTH.class_keys.large = {"]
    out += ['\t["%s"] = true,' % k for k in sorted(large)]
    out += ["}", "FOURTH.class_keys.single = {"]
    out += ['\t["%s"] = true,' % k for k in sorted(single)]
    out += ["}"]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    L, S = derive()
    print("large", len(L), "single", len(S), "large and single", len(L & S))
