#!/usr/bin/env python3
"""Round 182: the Executioner left enemy_blob for enemy_finisher. Regenerate, in both copies, the SHOT table (it now
covers enemy_finisher) and the three blob blocks (keyed on the enemy_blob keys: tools/round174_blob_tables.py). Each
block is cut at its load call at a line start (the round-174 lesson)."""
import os
import runpy
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_shot_tables as GS  # noqa: E402

SRC = r"C:\Users\vlady\Desktop\WH3_mod\mod_source\script\battle\mod\zz_test_deadly_onslaught.lua"
ANN = r"C:\Users\vlady\Desktop\WH3_mod\docs\WH3_auto_ability_annotated.lua"
HEAD = "-- GENERATED by tools/gen_shot_tables.py from unit_spec_abil, projectiles"
TAIL = "\nFOURTH.load_shot_table()\n"
live = open(SRC, encoding="utf-8").read()
keys = GS.keys_in(live)
block = GS.lua_block(GS.derive(keys))
for path in (SRC, ANN):
    s = open(path, encoding="utf-8", newline="").read()
    assert s.count(HEAD) == 1
    i = s.index(HEAD)
    j = s.index(TAIL, i) + len(TAIL)
    s = s[:i] + block + s[j:]
    assert s.count(TAIL) == 1 and s.count("function FOURTH.load_shot_table()") == 1
    open(path, "w", encoding="utf-8", newline="").write(s)
    print(path[-30:], "SHOT keys", len(keys))
runpy.run_path(os.path.join(os.path.dirname(os.path.abspath(__file__)), "round174_blob_tables.py"), run_name="__main__")
