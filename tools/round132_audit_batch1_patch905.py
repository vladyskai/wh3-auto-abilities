BEGIN = "-- BEGIN GENERATED RELOAD TABLE (tools/gen_reload_table.py; do not edit by hand)\n"
END = "-- END GENERATED RELOAD TABLE\n"


def reload_block():
    out = subprocess.run([sys.executable, os.path.join(TOOLS, "gen_reload_table.py")],
                         capture_output=True, text=True, encoding="utf-8", check=True).stdout
    assert out.startswith(BEGIN) and out.endswith(END), out[:80]
    return out


def apply_reload(s, block):
    a = s.index(BEGIN)
    b = s.index(END) + len(END)
    assert s.count(BEGIN) == 1 and s.count(END) == 1
    return s[:a] + block + s[b:]


