def entry_span(s, marker):
    a = s.index('\t{ marker = "%s",' % marker)
    assert s.count('\t{ marker = "%s",' % marker) == 1, marker
    b = s.index("ox = 0, oy = 0 },\n", a) + len("ox = 0, oy = 0 },\n")
    return a, b, s[a:b]


def apply_roster(s):
    for m, (trig, extra) in RETRIGGER.items():
        a, b, block = entry_span(s, m)
        assert block.count("\n") <= 5, (m, block)
        old = 'trigger = "metallurgy_melee",' if m.startswith(("enchanted_metallurgy", "master_of_alchemy")) \
            else 'trigger = "melee_unwavering",'
        assert old in block, (m, block)
        nb = block.replace(old, 'trigger = "%s",' % trig)
        if extra:
            nb = nb.replace("\t\tox = 0, oy = 0 },\n", "\t\t%s,\n\t\tox = 0, oy = 0 },\n" % extra)
        s = s[:a] + nb + s[b:]
    return s


